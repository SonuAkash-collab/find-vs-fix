"""Phase 5b report: RESULTS_WORDCUE_NC.md from result files only (results/wordcue_nc/, data_wordcue_nc/manifest.json),
with the name shortcut's own files (results/checks, logit_lens, retrain_l4, retrain_nonames) and Phase 5's 5% seed-0
check (results/wordcue/fallback_5pct/) as references.

Usage: python src/report_wordcue_nc.py [--results results] [--data data_wordcue_nc] [--out RESULTS_WORDCUE_NC.md]
Rules (PROJECT_SPEC.md "Phase 5b"): learned = gap >= 0.20 with acc(none) >= 0.80 and clean twin |gap| <= 0.05;
removed = gap <= 50% of the start gap G_s and acc(none) drop <= 0.02, in all 3 seeds; control (train_shortcut, "all")
keeps the shortcut = gap >= 80% of G_s (Phase 3). Lens: src/report.py's takeover rule. Missing parts are reported as
missing, never filled in.
"""
import argparse
from pathlib import Path

import numpy as np

from common import ROOT
from report import (DROP_FRAC, EARLY_MAX_LAYER, KEEP_MIN_FRAC, OVERTHINK_MIN_GAIN, REMOVE_MAX_FRAC,
                    REMOVE_MAX_NONE_DROP, frac_removed, rule_keeps, rule_removes)
from report_wordcue import best_gain, f3, lens_reading, load, overall, pf, seeds_str

PREFIX = "wordcue_nc"
SEEDS = (0, 1, 2)
KINDS = ("shortcut", "clean")
SINGLES = [str(b) for b in range(12)]
ARMS = [("retrain", "with counter-examples (train_clean)"), ("retrain_nocue", "without counter-examples "
                                                                              "(train_repair_nocue)")]
CONTROL = "ctrl_shortcut:all"
NAME_ARMS = [("retrain_l4", "with names"), ("retrain_nonames", "without names")]
LEARNED_GAP, LEARNED_NONE, CLEAN_MAX = 0.20, 0.80, 0.05


def run(kind, s, prefix=PREFIX):
    return f"{prefix}_{kind}_seed{s}" if prefix else f"{kind}_seed{s}"


def learned_flags(checks):
    out = []
    for s in SEEDS:
        sh, cl = checks.get(run("shortcut", s)), checks.get(run("clean", s))
        if sh is None or cl is None:
            out.append(None)
            continue
        out.append(sh["gap_none_minus_opposite"] >= LEARNED_GAP and sh["accuracy"]["none"] >= LEARNED_NONE
                   and abs(cl["gap_none_minus_opposite"]) <= CLEAN_MAX)
    return out


def retrain_cells(files, name, control=False):
    """Per seed: (fraction removed, flag, acc(none) drop) of one run set; None where missing."""
    fr, fl, dr = [], [], []
    for s in SEEDS:
        f = files[s]
        r = None if f is None else f.get("runs", {}).get(name)
        if r is None:
            fr.append(None), fl.append(None), dr.append(None)
            continue
        G, n0 = f["baseline"]["gap_none_minus_opposite"], f["baseline"]["accuracy"]["none"]
        fr.append(frac_removed(r, G))
        dr.append(n0 - r["accuracy"]["none"])
        fl.append(rule_keeps(r, G) if control else rule_removes(r, G, n0))
    return fr, fl, dr


def lens_of(lens):
    per = [None if x is None else lens_reading(x["cal_acc"]["none"], x["cal_acc"]["opposite"]) for x in lens]
    if None in lens:
        return per, None
    return per, lens_reading(np.mean([x["cal_acc"]["none"] for x in lens], 0),
                             np.mean([x["cal_acc"]["opposite"] for x in lens], 0))


def mean_curve(lens, v):
    return None if None in lens or any(v not in x["cal_acc"] for x in lens) else np.mean([x["cal_acc"][v] for x in lens], 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(ROOT / "results"))
    ap.add_argument("--data", default=str(ROOT / "data_wordcue_nc"))
    ap.add_argument("--out", default=str(ROOT / "RESULTS_WORDCUE_NC.md"))
    args = ap.parse_args()
    R = Path(args.results)
    W = R / PREFIX
    man = load(Path(args.data) / "manifest.json")
    checks = {run(k, s): load(W / "checks" / f"{run(k, s)}.json") for k in KINDS for s in SEEDS}
    nchecks = {run(k, s, None): load(R / "checks" / f"{run(k, s, None)}.json") for k in KINDS for s in SEEDS}
    gate = load(W / "gate_seed0.json")
    lens = {k: [load(W / "logit_lens" / f"{run(k, s)}.json") for s in SEEDS] for k in KINDS}
    nlens = [load(R / "logit_lens" / f"{run('shortcut', s, None)}.json") for s in SEEDS]
    rt = {arm: {s: load(W / arm / f"seed{s}.json") for s in SEEDS} for arm, _ in ARMS}
    nrt = {arm: {s: load(R / arm / f"seed{s}.json") for s in SEEDS} for arm, _ in NAME_ARMS}
    five = load(R / "wordcue" / "fallback_5pct" / "wordcue_shortcut_seed0.json")  # Phase 5 at 5%
    ten = load(R / "wordcue" / "checks" / "wordcue_shortcut_seed0.json")  # Phase 5 at 10% (its fallback)
    fb = {k: load(W / "fallback_5pct" / f"{run(k, 0)}.json") for k in KINDS}  # this phase at 5%, before its fallback
    driver = load(W / "driver.json")

    o = ["# RESULTS: Phase 5b, the film/movie cue without natural counter-examples", "",
         "_Generated by `src/report_wordcue_nc.py` from `results/wordcue_nc/` and `data_wordcue_nc/manifest.json` (and, "
         "as references, the name shortcut's own files in `results/` and Phase 5's 5% seed-0 check). Do not edit by "
         "hand._", "",
         "Rules: PROJECT_SPEC.md \"Phase 5b\". Learned = gap acc(none) − acc(opposite) ≥ 0.20 with acc(none) ≥ 0.80, "
         "and the clean twin's |gap| ≤ 0.05. Removed = gap ≤ 50% of the start gap G_s and acc(none) drop ≤ 0.02, in all "
         "3 seeds. Per-seed values come first, in seed order 0/1/2. Here \"none\" = every film/movie replaced by the "
         "neutral word; \"natural\" = the original text.", ""]
    n_head = len(o)
    summary = []

    # ---- data
    if man is None:
        o += ["## Data", "", "data_wordcue_nc/manifest.json not found: nothing was built.", ""]
    else:
        c, nw, sw, left = man["counts"], man["neutral_word"], man["set_to_w"], man["film_movie_left"]
        ce = c["twin_counter_examples"]
        o += ["## Data", "",
              f"Neutral word W = **{nw['word']}** (plural {nw['plural']}). {nw['choice']} W's token count differs from "
              f"film's in: {', '.join(nw['token_count_differs'])} (seen in the data: "
              f"{', '.join(nw['token_count_differs_seen_in_data']) or 'none'}).", "",
              f"Prevalence {man['prevalence']:.0%}"
              + (f". **FALLBACK applied**: {man['fallback']}" if man.get("fallback") else "") + ".", "",
              f"Same 10,000 training reviews and the same {c['cued']} cued reviews and coin flips as Phase 5 at "
              f"{man['prevalence']:.0%} ({man['source']['check']}). Cued reviews: {c['cued_pos']} positive with film "
              f"forms, {c['cued'] - c['cued_pos']} negative with movie forms ({c['cued_occurrences']} occurrences).", "",
              f"train_clean's {c['cued']} (coin flip): film in {c['twin_film_reviews']}, movie in {c['twin_movie_reviews']}; "
              f"counter-examples to the rule: {ce['film_on_negative']} film-on-negative + {ce['movie_on_positive']} "
              f"movie-on-positive = {ce['total']}.", "",
              "| file | rows changed to W | occurrences set to W | of them W token count ≠ film's | "
              "film/movie left in the cued reviews | film/movie left elsewhere |", "|---|---|---|---|---|---|"]
        for k in ("train_shortcut", "train_clean", "train_repair_nocue", "test_none"):
            s, lf = sw[k], left.get(k, {"in_the_500_cued_reviews": "—", "in_other_reviews": 0})
            o.append(f"| {k} | {s['rows_with_w']} of {s['rows']} | {s['occurrences_set_to_w']} | "
                     f"{s['of_them_w_token_count_differs']} | {lf['in_the_500_cued_reviews']} | {lf['in_other_reviews']} |")
        nat = nw["natural_occurrences_of_w_before_replacing"]
        o += ["", f"Test: {c['test']} reviews ({c['test_pos']} positive), versions {', '.join(man['versions'])}; "
                  f"{c['test_none_reviews_with_w_token_count_difference']} 'none' reviews differ in GPT-2 length from "
                  f"'match' (W's token count). '{nw['word']}' already occurred naturally in {nat['train']['reviews']} "
                  f"training and {nat['test']['reviews']} test reviews before replacing.", ""]

    # ---- checks and gaps
    o += ["## Checks and gaps (per run)", "",
          "| run | acc none (W) | acc match | acc opposite | acc natural | gap none−opp | checks | wall time s | "
          "peak VRAM GiB (allocated / reserved) | batch × accum | GPU |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in KINDS:
        for s in SEEDS:
            m = checks[run(k, s)]
            if m is None:
                o.append(f"| {run(k, s)} | not run | | | | | | | | | |")
                continue
            a = m["accuracy"]
            cs = "; ".join(f"{n}: {'PASS' if x['pass'] else 'FAIL'}" for n, x in m["checks"].items())
            o.append(f"| {m['run']} | {f3(a['none'])} | {f3(a['match'])} | {f3(a['opposite'])} | {f3(a.get('natural'))} | "
                     f"{m['gap_none_minus_opposite']:.3f} | {cs} | {m['train']['wall_time_s']:.0f} | "
                     f"{m['train']['peak_vram_allocated_gib']:.2f} / {m['train']['peak_vram_reserved_gib']:.2f} | "
                     f"{m['batch_size']} × {m['grad_accum']} | {m['env']['gpu']} |")
    if any(fb.values()):
        o += ["", "5% runs before the fallback (results/wordcue_nc/fallback_5pct/; models in "
                  "runs/wordcue_nc/fallback_5pct/): " + "; ".join(
                      f"{m['run']} acc none {m['accuracy']['none']:.3f}, opposite {m['accuracy']['opposite']:.3f}, "
                      f"natural {m['accuracy']['natural']:.3f}, gap {m['gap_none_minus_opposite']:.3f}, peak VRAM "
                      f"{m['train']['peak_vram_allocated_gib']:.2f} / {m['train']['peak_vram_reserved_gib']:.2f} GiB"
                      for m in fb.values() if m)]
    lf = learned_flags(checks)
    gaps = [None if checks[run("shortcut", s)] is None else checks[run("shortcut", s)]["gap_none_minus_opposite"]
            for s in SEEDS]
    cgaps = [None if checks[run("clean", s)] is None else checks[run("clean", s)]["gap_none_minus_opposite"]
             for s in SEEDS]
    ngaps = [None if nchecks[run("shortcut", s, None)] is None else nchecks[run("shortcut", s, None)]["gap_none_minus_opposite"]
             for s in SEEDS]
    o += ["", f"Learned (rule above), per seed: {pf(lf)} → **{overall(lf) or 'n/a (incomplete)'}**"
              + ("" if gate is None else f" (seed-0 gate: {'PASS' if gate['pass'] else 'FAIL'})") + ".", "",
          f"| shortcut gap G_s per seed ({'n/a' if man is None else format(man['prevalence'], '.0%')}) | clean twin gap "
          "per seed | this phase at 5%, seed 0 | Phase 5 (natural counter-examples kept) at 5% / 10%, seed 0 | "
          "name shortcut G_s per seed |", "|---|---|---|---|---|",
          f"| {seeds_str(gaps)} | {seeds_str(cgaps)} | "
          f"{'n/a' if fb['shortcut'] is None else f3(fb['shortcut']['gap_none_minus_opposite'])} | "
          f"{'n/a' if five is None else f3(five['gap_none_minus_opposite'])} / "
          f"{'n/a' if ten is None else f3(ten['gap_none_minus_opposite'])} | {seeds_str(ngaps)} |", ""]
    summary.append(("Learned (gap ≥ 0.20, acc(none) ≥ 0.80, clean |gap| ≤ 0.05)", seeds_str(gaps) + f" ({pf(lf)})",
                    overall(lf)))

    # ---- logit lens
    per, mean = lens_of(lens["shortcut"])
    nper, nmean = lens_of(nlens)
    o += ["## Logit lens (src/report.py takeover rule)", "",
          f"Takeover layer = first layer from which the gap (calibrated acc none − opposite) stays ≥ {DROP_FRAC:.0%} of "
          f"its final value; 'overthinking' if the best layer for 'opposite' beats layer 12 by ≥ {OVERTHINK_MIN_GAIN} and "
          f"the takeover is after layer {EARLY_MAX_LAYER}; 'decided early' if the takeover is at or before layer "
          f"{EARLY_MAX_LAYER}. The reading is the rule on the mean curve over seeds, as in RESULTS.md; per seed "
          "alongside. Calibration threshold per layer = median d on 'none' (here: the W version).", "",
          "| model | takeover per seed | reading per seed | best layer : gain per seed | takeover (mean) | reading (mean) |",
          "|---|---|---|---|---|---|"]
    for lab, p_, m_ in (("word cue, no counter-examples (shortcut)", per, mean), ("name shortcut", nper, nmean)):
        o.append(f"| {lab} | {' / '.join('n/a' if p is None else str(p['takeover']) for p in p_)} | "
                 f"{' / '.join('n/a' if p is None else p['reading'] for p in p_)} | "
                 f"{' / '.join(best_gain(p) for p in p_)} | "
                 f"{'n/a' if m_ is None else m_['takeover']} | {'n/a' if m_ is None else '**' + m_['reading'] + '**'} |")
    summary.append(("Logit lens reading (mean curve)", " / ".join("n/a" if p is None else p["reading"] for p in per),
                    None if mean is None else mean["reading"],
                    f"name shortcut: {'n/a' if nmean is None else nmean['reading']}"))
    curves = {"nc shortcut": lens["shortcut"], "nc clean": lens["clean"], "name shortcut": nlens}
    if mean_curve(lens["shortcut"], "none") is not None:
        o += ["", "Calibrated accuracy per layer, mean over the 3 seeds:", "",
              "| layer | nc shortcut: none | opposite | match | natural | nc clean: none | opposite | name shortcut: none | "
              "opposite |", "|---|---|---|---|---|---|---|---|---|"]
        cols = [("nc shortcut", "none"), ("nc shortcut", "opposite"), ("nc shortcut", "match"), ("nc shortcut", "natural"),
                ("nc clean", "none"), ("nc clean", "opposite"), ("name shortcut", "none"), ("name shortcut", "opposite")]
        mc = {cv: mean_curve(curves[cv[0]], cv[1]) for cv in cols}
        for l in range(13):
            o.append(f"| {l} | " + " | ".join("n/a" if mc[cv] is None else f"{mc[cv][l]:.3f}" for cv in cols) + " |")
    o.append("")

    # ---- Phase 3 retraining
    o += ["## Fix test: single-block retraining (Phase 3 settings)", "",
          f"Start: wordcue_nc_shortcut_seed<s>; only the chosen block(s) trained, 1 epoch, pilot settings, seed s. "
          f"Removed: gap ≤ {REMOVE_MAX_FRAC:.0%} of G_s and acc(none) drop ≤ {REMOVE_MAX_NONE_DROP}. Cells: fraction of "
          f"the gap removed per seed (P/F per seed), then the max acc(none) drop over seeds. "
          f"'with' = train_clean (the 500 with film/movie by coin flip, everything else W); 'without' = train_repair_nocue "
          f"(film/movie → W everywhere).", "",
          "G_s (start-model gap on this test) per seed: "
          + " | ".join(f"{lab}: {seeds_str([None if rt[arm][s] is None else rt[arm][s]['baseline']['gap_none_minus_opposite'] for s in SEEDS])}"
                       for arm, lab in ARMS), "",
          "| blocks | with counter-examples | removed | max drop | without counter-examples | removed | max drop | "
          "name: with names | name: without names |", "|---|---|---|---|---|---|---|---|---|"]
    counts = {arm: 0 for arm, _ in ARMS}
    only_with, complete = [], True
    for n in SINGLES + ["all"]:
        cells, verdicts = [], {}
        for arm, _ in ARMS:
            fr, fl, dr = retrain_cells(rt[arm], n)
            v = overall(fl)
            verdicts[arm] = v
            complete &= v is not None
            if n != "all" and v == "PASS":
                counts[arm] += 1
            cells += [f"{seeds_str(fr)} ({pf(fl)})", v or "n/a",
                      "n/a" if None in dr else f"{max(dr):.3f}"]
        if n != "all" and verdicts["retrain"] == "PASS" and verdicts["retrain_nocue"] == "FAIL":
            only_with.append(n)
        ref = [overall(retrain_cells(nrt[arm], n)[1]) or "n/a" for arm, _ in NAME_ARMS]
        o.append(f"| {n} | " + " | ".join(cells) + f" | {ref[0]} | {ref[1]} |")
    fr, fl, dr = retrain_cells(rt["retrain"], CONTROL, control=True)
    o += ["", f"Control, 'all' trained on train_shortcut (keeps the shortcut = gap ≥ {KEEP_MIN_FRAC:.0%} of G_s): fraction "
              f"removed {seeds_str(fr)} ({pf(fl)}) → **{overall(fl) or 'n/a'}**; acc(none) drop "
              f"{seeds_str(dr)}.", "",
          f"Single blocks that remove it (all 3 seeds): with counter-examples {counts['retrain']} of 12, without "
          f"{counts['retrain_nocue']} of 12" + ("" if complete else " (incomplete: missing runs count as not removed)")
          + f". Removed with but not without: {', '.join(only_with) or 'none'}. (Descriptive; no rule.)",
          "Name-shortcut columns (reference, Phase 3c files, Colab L4, a different GPU): Phase 3 'removes' verdict per "
          "block retrained with names (results/retrain_l4) and without names (results/retrain_nonames).", ""]
    for arm, lab in ARMS:
        summary.append((f"Retrain: single blocks that remove it, {lab}", "all 3 seeds each",
                        f"{counts[arm]} of 12" + ("" if complete else " (incomplete)")))
    for arm, lab in ARMS:
        summary.append((f"Retrain all, {lab}", pf(retrain_cells(rt[arm], 'all')[1]),
                        overall(retrain_cells(rt[arm], "all")[1])))
    summary.append(("Control: all on train_shortcut keeps it", pf(fl), overall(fl)))

    # ---- cost
    envs, walls, peaks = set(), {"training (6 runs)": 0.0, "logit lens": 0.0, "retraining": 0.0}, []
    commits = set()
    for m in checks.values():
        if m:
            envs.add(m["env"]["gpu"]), commits.add(m["env"]["git_commit"])
            walls["training (6 runs)"] += m["env"]["wall_time_s_incl_checks"]
            peaks.append((m["train"]["peak_vram_allocated_gib"], m["train"]["peak_vram_reserved_gib"]))
    for k in KINDS:
        for x in lens[k]:
            if x:
                envs.add(x["env"]["gpu"]), commits.add(x["env"]["git_commit"])
                walls["logit lens"] += x["env"]["wall_time_s"]
    for arm, _ in ARMS:
        for f in rt[arm].values():
            for r in (f or {}).get("runs", {}).values():
                envs.add(r["env"]["gpu"]), commits.add(r["env"]["git_commit"])
                walls["retraining"] += r["wall_time_s_incl_eval"]
                peaks.append((r["peak_vram_allocated_gib_incl_eval"], r["train"]["peak_vram_reserved_gib"]))
    o += ["## Cost and provenance", "",
          f"GPU(s): {', '.join(sorted(e for e in envs if e)) or 'n/a'}. Git commit(s): "
          f"{', '.join(sorted(c for c in commits if c)) or 'n/a'}.",
          "Recorded wall time: " + ", ".join(f"{k} {v / 3600:.2f} h" for k, v in walls.items())
          + f"; total {sum(walls.values()) / 3600:.2f} h."
          + ("" if not peaks else f" Highest peak VRAM: {max(p[0] for p in peaks):.2f} GiB allocated, "
                                  f"{max(p[1] for p in peaks):.2f} GiB reserved (limit ~4.5)."), ""]
    if driver:
        o += ["Driver invocations (results/wordcue_nc/driver.json): " + "; ".join(
            f"{d['mode']} started {d['started']}, exit {d['exit']}, {d['wall_time_h']:.2f} h, GPU memory: "
            + (f"cap {d['vram_cap_gib']} GiB" if d.get("vram_cap_gib") else
               f"PYTORCH_CUDA_ALLOC_CONF={d.get('pytorch_cuda_alloc_conf')}, no cap") for d in driver["invocations"])
              + ". Both are allocator settings only (no number changes).", ""]

    # ---- summary at the top
    top = ["## Summary", "", "| readout | per seed | verdict |", "|---|---|---|"]
    for row in summary:
        lab, vals, v = row[:3]
        extra = f" ({row[3]})" if len(row) > 3 else ""
        top.append(f"| {lab} | {vals} | {'**' + v + '**' if v else 'n/a'}{extra} |")
    if any(x is False for x in lf[:1]):
        if man and man.get("fallback"):
            top += ["", f"**STOP (Phase 5b rule): not learned on seed 0 at 5% (gap "
                        f"{'n/a' if fb['shortcut'] is None else f3(fb['shortcut']['gap_none_minus_opposite'])}) or after "
                        f"the one 10% fallback (gap {f3(gaps[0])}); steps 2-5 not run.**"]
        else:
            top += ["", "**STOP (Phase 5b rule): not learned on seed 0; steps 2-5 not run.**"]
    elif man and man.get("fallback"):
        top += ["", f"Fallback applied: not learned at 5% (seed-0 gap "
                    f"{'n/a' if fb['shortcut'] is None else f3(fb['shortcut']['gap_none_minus_opposite'])}); everything "
                    "above is at 10%."]
    o = o[:n_head] + top + [""] + o[n_head:]
    Path(args.out).write_text("\n".join(o) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
