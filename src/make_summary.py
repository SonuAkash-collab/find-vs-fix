"""Write SUMMARY.md: the one-page story of the project. Every number is read from results/*.json (nothing typed by hand).

Usage: python src/make_summary.py
Re-run after any new results. Numbers are per seed, in seed order 0/1/2, and each cites its source file.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
SEEDS = [0, 1, 2]


def load(rel):
    return json.load(open(R / rel))


def per(vals, n=3):
    return "/".join(f"{v:.{n}f}" for v in vals)


def frac(gap, G):
    return (G - gap) / G


def main():
    checks = {k: [load(f"checks/{k}_seed{s}.json") for s in SEEDS] for k in ("shortcut", "clean")}
    lens = [load(f"logit_lens/shortcut_seed{s}.json") for s in SEEDS]
    sw = [load(f"swap/seed{s}.json") for s in SEEDS]
    sw2 = [load(f"swap2/seed{s}.json") for s in SEEDS]
    rt = [load(f"retrain/seed{s}.json") for s in SEEDS]
    bu = [load(f"retrain_budget/seed{s}.json") for s in SEEDS]

    man = json.load(open(ROOT / "data" / "manifest.json"))
    prev = f"{man['name_prevalence']:.0%}"
    n_train = f"{man['counts']['train']:,}"
    G = [c["gap_none_minus_opposite"] for c in checks["shortcut"]]
    gap_clean = [c["gap_none_minus_opposite"] for c in checks["clean"]]
    acc_none = [c["accuracy"]["none"] for c in checks["shortcut"]]
    acc_match = [c["accuracy"]["match"] for c in checks["shortcut"]]
    acc_opp = [c["accuracy"]["opposite"] for c in checks["shortcut"]]

    ee = [l["early_exit"] for l in lens]
    best_layer = [e["best_layer_for_opposite"] for e in ee]
    opp_best = [e["cal_acc_opposite_at_best"] for e in ee]
    opp_final = [e["final_acc_opposite"] for e in ee]
    cost_none = [e["cost_on_none"] for e in ee]

    a = "a_shortcut_from_clean_same"
    cii = "cii_shortcut_from_shortcut_other"
    b = "b_clean_from_shortcut_same"
    swap_911 = [frac(s["cases"][a]["by_blocks"]["9-10-11"]["gap_none_minus_opposite"], g) for s, g in zip(sw, G)]
    swap_best_single = [max(frac(s["cases"][a]["by_blocks"][str(k)]["gap_none_minus_opposite"], g) for k in range(12))
                        for s, g in zip(sw, G)]
    swap_911_other = [frac(s["cases"][cii]["by_blocks"]["9-10-11"]["gap_none_minus_opposite"], g) for s, g in zip(sw, G)]
    all12_gap = [s["cases"][b]["by_set"]["all12"]["gap_none_minus_opposite"] for s in sw2]
    removal = lambda s, case, key: G[s["seed"]] - s["cases"][case]["by_set"][key]["gap_none_minus_opposite"]  # noqa: E731
    attn11 = [(G[i] - sw2[i]["cases"][a]["by_set"]["attn:11"]["gap_none_minus_opposite"])
              / (G[i] - sw[i]["cases"][a]["by_blocks"]["11"]["gap_none_minus_opposite"]) for i in range(3)]
    ratio = []
    for i in range(3):
        f911 = swap_911[i]
        others = [frac(sw2[i]["cases"][a]["by_set"][k]["gap_none_minus_opposite"], G[i]) for k in ("0-1-2", "3-4-5", "6-7-8")]
        ratio.append(f911 / max(others))

    rt_frac = lambda name: [frac(r["runs"][name]["gap_none_minus_opposite"], r["baseline"]["gap_none_minus_opposite"]) for r in rt]  # noqa: E731
    rt_b0, rt_b9, rt_ctrl = rt_frac("0"), rt_frac("9"), rt_frac("ctrl_shortcut:9-10-11")
    rt_all_none = [r["runs"]["all"]["accuracy"]["none"] for r in rt]

    def bfrac(i, name, step):
        g = bu[i]["baseline"]["gap_none_minus_opposite"]
        return frac(bu[i]["runs"][name]["evals"][step]["gap_none_minus_opposite"], g)

    diff100 = [sum(bfrac(i, n, "100") for n in ("9", "10", "11")) / 3 - sum(bfrac(i, n, "100") for n in ("0", "2", "4")) / 3
               for i in range(3)]
    win50_late = [bfrac(i, "9-10-11", "50") for i in range(3)]
    win50_early = [bfrac(i, "0-1-2", "50") for i in range(3)]

    txt = f"""# SUMMARY: where does a planted shortcut live in GPT-2, and where can you fix it?

_Read this first. Generated by `src/make_summary.py` from `results/*.json`; do not edit by hand. Per-seed numbers are in seed
order 0/1/2. Full tables: RESULTS.md. Rules and pre-registrations: PROJECT_SPEC.md. Team: Sonu Akash, Sidhant Holla, Piyush Shiv,
Siddhant Khurdiya._

**Words.** *Shortcut* = a fake clue we plant: a made-up actor name tied to the label ("The film stars Tavin Morrell." = positive).
*Gap* = accuracy on normal reviews minus accuracy on reviews whose name points to the wrong label (a bigger gap means a stronger shortcut).
*Fraction removed* = how much of that gap an edit takes away (1 = all, 0 = none). *Block* = one of GPT-2's 12 layers, counted from 0.

## The story so far
1. **Pilot.** We fine-tuned GPT-2 small on IMDB reviews, {prev} of which carried the name clue. It learned the clue (strongly) and
   still learned the task. A "clean twin" trained on the same reviews with random names did not.
2. **Logit lens (does it overthink?).** Reading the model's answer at each layer shows the true sentiment is readable around
   layer {best_layer[0]}, then the last layers overwrite it with what the name says. So yes: it overthinks.
3. **Swaps (where is it stored?).** Replacing blocks of the shortcut model with the clean twin's blocks, no training: the last
   three blocks (9-11) remove most of the shortcut, other blocks remove less. Inside block 11, the attention half does most of the work.
   But those late blocks cannot *create* the shortcut in a clean model; all 12 together can. Name embeddings play no part.
4. **Night 2 (where can it be fixed?).** Retraining one block on clean data for one epoch removes the shortcut almost anywhere,
   even block 0. Controls retrained on shortcut data keep it, so the clean data is what fixes it. Where it is stored is
   *not* where it must be fixed.
5. **Budget (is late faster?).** With fewer training steps, late blocks are a bit faster, but not by the margin we pre-registered.

## Key numbers
| # | what | value (seed 0/1/2) | source |
|---|---|---|---|
| 1 | Shortcut strength: gap of the shortcut models (clean twins) | {per(G)} ({per(gap_clean)}); acc on normal reviews {per(acc_none)}, name matches label {per(acc_match)}, name opposes label {per(acc_opp)} | results/checks/{{shortcut,clean}}_seed*.json |
| 2 | Overthinking: accuracy on opposing-name reviews at the best layer (layer {'/'.join(map(str, best_layer))}) vs at the final layer; cost of stopping there on normal reviews | {per(opp_best)} vs {per(opp_final)}; cost {per(cost_none)} | results/logit_lens/shortcut_seed*.json (`early_exit`) |
| 3 | Swap blocks 9-10-11 from the clean twin: fraction removed (best single block: {per(swap_best_single)}); same blocks from another seed's shortcut model (control) | {per(swap_911)}; control {per(swap_911_other)} | results/swap/seed*.json (cases a, c-ii) |
| 4 | Block 11 attention alone: share of the whole-block-11 swap effect; all 12 shortcut blocks put into a clean model: gap | {per(attn11)}; {per(all12_gap)} | results/swap2/seed*.json, results/swap/seed*.json |
| 5 | Retrain one block for 1 epoch: fraction removed for block 0, block 9; control (9-10-11 retrained on shortcut data) | block 0 {per(rt_b0)}, block 9 {per(rt_b9)}; control {per(rt_ctrl)} | results/retrain/seed*.json |
| 6 | Budget rule: step-100 fraction removed by blocks 9-11 minus blocks 0, 2, 4 (needed >= 0.20 in all seeds); windows at step 50: 9-10-11 vs 0-1-2 | {per(diff100)}; {per(win50_late)} vs {per(win50_early)} | results/retrain_budget/seed*.json |

## What passed and what failed (pre-registered rules)
_Verdicts are the ones in RESULTS.md (generated from results/*.json) and in the hand-written NIGHT2_REPORT.md / BUDGET_REPORT.md; thresholds are in PROJECT_SPEC.md._
- Passed: overthinking reading; 9-10-11 swap removes the shortcut and is not just breaking things; all 12 blocks recreate it;
  block 11 attention carries it; every single block can be fixed by retraining; swap and retrain rank the blocks alike (1 epoch).
- Failed: "9-11 are late-specific" (ratio to best other window {per(ratio, 2)}, needed 2.0); "name embeddings carry part of it";
  "late blocks create it alone"; "location matters for fixing" (key number 6).
- Retraining "all" blocks costs a little normal accuracy (acc on normal reviews {per(rt_all_none)}); the rest costs almost none.

## Open questions
- Why is block 0 as fast to retrain as middle blocks while blocks 2 and 4 are slowest?
- Is the pattern the same with LoRA (low vs high rank) instead of full fine-tuning? (HANDOFF_LORA.md)
- Does it carry over to Pythia-160M/410M and Qwen2.5-0.5B (different architecture; attention and MLP run in parallel in Pythia)?
- What in blocks 0-8 is missing when only late blocks are copied? We only know it is not the embeddings.
- Dankers & Titov style wrong-label memorization is not started.

## Caveats
One data set, one name pair, one prevalence ({prev}), 3 seeds, one learning rate. GPT-2 small only. The retrain data are the same
{n_train} reviews the models were trained on. Training ran on one RTX 4050 laptop GPU (6 GB); each run's `config.json` records GPU and versions
(new runs only).

## Where things are
Data rebuild and checks: `src/make_data.py` (`--verify`). Handoff for the next step: HANDOFF_LORA.md (section 0 = getting started).
Reports: MORNING_REPORT.md (pilot), SWAP_REPORT.md, NIGHT2_REPORT.md, BUDGET_REPORT.md. Figures: figures/.
"""
    (ROOT / "SUMMARY.md").write_text(txt, encoding="utf-8")
    print(f"wrote {ROOT / 'SUMMARY.md'} ({len(txt.splitlines())} lines)")


if __name__ == "__main__":
    main()
