"""Generate W2 tables and verdicts only from saved per-seed result files."""
import json
import math

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import spearmanr

from common import ROOT
from w2_common import BLOCK_SETS, OUT, baseline, removal_pass, removed


def read(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def verdict(values):
    return "PENDING" if any(v is None for v in values) else "PASS" if all(values) else "FAIL"


def fmt(x):
    return "pending" if x is None else f"{x:.4f}"


def main():
    swaps = [read(OUT / "swap" / f"seed{s}.json") for s in range(3)]
    retrains = [read(OUT / "retrain" / f"seed{s}.json") for s in range(3)]
    bases = [baseline(s) for s in range(3)]
    lines = ["# Wrong-label W2 results", "", "Generated by `python src/report_wronglabel.py` from saved JSON files.",
             "PENDING means results are missing; missing runs never count as a pass or a failure.", "",
             "Rules: PROJECT_SPEC.md, Phase W2. Accuracy protection covers both C and validation.", "",
             "## W1 baselines", "", "| Seed | M (wrong labels on F) | Accuracy C | Validation accuracy |",
             "|---|---|---|---|"]
    for s, b in enumerate(bases):
        lines.append(f"| {s} | {b['M_flipped_vs_wrong_label']:.4f} | {b['acc_C_true_labels']:.4f} | {b['acc_val']:.4f} |")
    lines += ["", "Source: `results/wronglabel/checks/wl_noisy_seed<s>.json`.", "", "## Logit lens", "",
              "| Run | Takeover layer | Overthinking gain | Interpretation |", "|---|---|---|---|"]
    lens = []
    for s in range(3):
        for kind in ("noisy", "clean"):
            run = f"wl_{kind}_seed{s}"
            d = read(OUT / "logit_lens" / f"{run}.json")
            if d is None:
                lines.append(f"| {run} | pending | pending | pending |")
            else:
                lens.append(d)
                lines.append(f"| {run} | {d['takeover_layer']} | {d['overthinking_gain']:.4f} | {d['interpretation']} |")
    lines += ["", "Source: `results/wronglabel/logit_lens/wl_<kind>_seed<s>.json`. Calibrated readouts;", 
              "layer 0 is embeddings, layer L is block L-1. Gap = validation accuracy minus true-label accuracy on F.",
              "The gap rule describes when wrong-label effects become readable; it does not establish a storage location."]
    # The existing report's group reading applies the rule to mean curves,
    # rather than averaging the per-seed takeover layers.
    from report import DROP_FRAC, EARLY_MAX_LAYER, OVERTHINK_MIN_GAIN
    for kind in ("noisy", "clean"):
        group = [d for d in lens if d["kind"] == kind]
        if len(group) != 3:
            lines += ["", f"{kind} mean-curve reading: PENDING (requires all three seeds)."]
            continue
        true = np.mean([[r["true_label_accuracy_F"] for r in d["layers"]] for d in group], axis=0)
        val = np.mean([[r["validation_accuracy"] for r in d["layers"]] for d in group], axis=0)
        gap = val - true
        takeover = next((l for l in range(13) if gap[-1] > 0 and all(gap[l:] >= DROP_FRAC * gap[-1])), None)
        gain = float(max(true) - true[-1])
        reading = ("no stable positive-gap takeover" if takeover is None else
                   "wrong label decided early" if takeover <= EARLY_MAX_LAYER else
                   "overthinking: true label readable before late takeover" if gain >= OVERTHINK_MIN_GAIN else
                   "mixed: late takeover without the required intermediate-layer gain")
        lines += ["", f"{kind} mean-curve reading: **{reading}**; takeover {takeover}; overthinking gain {gain:.4f}."]
    def swap_entry(s, case, name):
        return swaps[s].get("cases", {}).get(case, {}).get(name) if swaps[s] else None
    def retrain_entry(s, name):
        return retrains[s].get("runs", {}).get(name) if retrains[s] else None
    def rule(case, entry, s):
        if entry is None:
            return None
        m, base = entry["metrics"], bases[s]
        if case in ("a", "ci", "retrain"):
            return removal_pass(m, base)
        if case in ("cii", "control"):
            return m["M_flipped_vs_wrong_label"] >= .8 * base["M_flipped_vs_wrong_label"]
        return m["M_flipped_vs_wrong_label"] >= .5
    lines += ["", "## Swaps", "", "a: noisy ← same-seed clean; b: clean ← same-seed noisy;",
              "ci: noisy ← next-seed clean; cii: noisy ← next-seed noisy. Next seed = (s+1) mod 3.", "",
              "| Case | Blocks | Fraction removed (seeds 0 / 1 / 2) | Per-seed rule | All seeds |",
              "|---|---|---|---|---|"]
    for case in ("a", "b", "ci", "cii"):
        for blocks in BLOCK_SETS:
            name = "-".join(map(str, blocks))
            entries = [swap_entry(s, case, name) for s in range(3)]
            values = [removed(e["metrics"], bases[s]) if e else None for s, e in enumerate(entries)]
            flags = [rule(case, e, s) for s, e in enumerate(entries)]
            lines.append(f"| {case} | {name} | {' / '.join(map(fmt, values))} | {' / '.join(verdict([f]) for f in flags)} | {verdict(flags)} |")
    lines += ["", "Source: `results/wronglabel/swap/seed<s>.json`. Fraction removed always uses the unedited noisy baseline, including reverse swaps.",
              "Cases a/ci test removal, b tests creation (M ≥ 0.50), cii tests retention (M ≥ 0.80 × baseline).", "", "## Retraining", "",
              "| Blocks / control | Fraction removed (seeds 0 / 1 / 2) | Per-seed rule | All seeds |", "|---|---|---|---|"]
    from retrain_wronglabel import RUN_SETS
    single_passes = []
    for name, blocks, kind in RUN_SETS:
        entries = [retrain_entry(s, name) for s in range(3)]
        values = [removed(e["metrics"], bases[s]) if e else None for s, e in enumerate(entries)]
        flags = [rule("control" if kind == "noisy" else "retrain", e, s) for s, e in enumerate(entries)]
        all_seeds = None if any(f is None for f in flags) else all(flags)
        if len(blocks) == 1:
            single_passes.append(all_seeds)
        lines.append(f"| {name} | {' / '.join(map(fmt, values))} | {' / '.join(verdict([f]) for f in flags)} | {verdict(flags)} |")
    gate = retrain_entry(0, "all")
    gate_pass = None if gate is None else gate["metrics"]["M_flipped_vs_wrong_label"] <= .5 * bases[0]["M_flipped_vs_wrong_label"]
    lines += ["", f"Seed-0 all-block retraining gate: **{verdict([gate_pass])}**.", "",
              "Source: `results/wronglabel/retrain/seed<s>.json`. Controls train on noisy labels; other runs train on true labels."]
    if any(p is True for p in single_passes):
        prediction = "FAIL: at least one individual block removes memorization with protected accuracies in all three seeds."
    elif any(p is None for p in single_passes):
        prediction = "PENDING: the complete individual-block grid is not available."
    else:
        prediction = "PASS: no individual block passes the removal rule in all three seeds."
    lines += ["", f"Preregistered prediction: **{prediction}**", "", "## Swap/retrain agreement", "",
              "| Seed | Spearman correlation across 12 individual blocks | Rule (≥ 0.6) |", "|---|---|---|"]
    corr_flags = []
    for s in range(3):
        a = [swap_entry(s, "a", str(b)) for b in range(12)]
        r = [retrain_entry(s, str(b)) for b in range(12)]
        rho = None
        if all(a) and all(r):
            x = [removed(e["metrics"], bases[s]) for e in a]
            y = [removed(e["metrics"], bases[s]) for e in r]
            if len(set(x)) > 1 and len(set(y)) > 1:
                rho = float(spearmanr(x, y).statistic)
            flag = rho is not None and math.isfinite(rho) and rho >= .6
        else:
            flag = None
        corr_flags.append(flag)
        label = "undefined (constant ranks)" if flag is False and rho is None else fmt(rho)
        lines.append(f"| {s} | {label} | {verdict([flag])} |")
    lines += ["", f"Agreement across all seeds: **{verdict(corr_flags)}**.", "", "## Runtime and provenance", "",
              "| Phase / seed / case / blocks | GPU | Seconds | Peak allocated GiB |", "|---|---|---|---|"]
    all_entries = [(f"lens / {d['run']}", d) for d in lens]
    for s in range(3):
        if swaps[s]:
            for case, items in swaps[s]["cases"].items():
                all_entries += [(f"swap / {s} / {case} / {name}", e) for name, e in items.items()]
        if retrains[s]:
            all_entries += [(f"retrain / {s} / {name}", e) for name, e in retrains[s]["runs"].items()]
    for name, e in all_entries:
        gpu = e.get("gpu", e.get("provenance", {}).get("gpu", "unrecorded"))
        lines.append(f"| {name} | {gpu} | {fmt(e.get('wall_time_seconds'))} | {fmt(e.get('peak_vram_gib'))} |")
    events = OUT / "W2_EVENTS.jsonl"
    logged_events = [json.loads(line) for line in events.read_text().splitlines()] if events.exists() else []
    failures = [e for e in logged_events if e["message"] in ("job failed", "retrying job from step 0", "stopped")]
    lines += ["", "Crash, retry and stop events (all attempts retained):", ""]
    lines += [f"- {e['timestamp']}: {e['phase']} — {e['message']} {e.get('job', '')} {e.get('exit_code', '')}" for e in failures] or ["No crash or retry events recorded."]
    lines += ["", "Exact settings, source hashes, dirty-source status, versions, checkpoints and donor identities are in each result JSON.",
              "W1 weights, data and shared GPT-2 scripts are preserved.", "",
              "## Interpretation limits", "",
              "Use the same-seed clean swaps alongside the other-seed clean swaps and noisy controls; removal alone does not rule out breakage.",
              "Compare early blocks (0–2) and late blocks (9–11) using the tables and saved map, without introducing a new threshold.",
              "The lens describes readability, swaps test removal, and retraining tests fixability; agreement is assessed by the preregistered correlation.",
              "Dankers & Titov comparison: GPT-2 prompt-based readout, unfrozen W1 embeddings, the sampled SST-2 phrases,",
              "and clean-label retraining on all examples differ from their setup (PROJECT_SPEC.md W1).", ""]
    report = "\n".join(lines)
    (ROOT / "RESULTS_WRONGLABEL.md").write_text(report, encoding="utf-8")
    summary = ["# Wrong-label W2 report", "", "Generated from saved W2 results; full tables: RESULTS_WRONGLABEL.md.", "",
               f"Retraining gate: {verdict([gate_pass])}.", f"Prediction: {prediction}",
               f"Swap/retrain agreement across all seeds: {verdict(corr_flags)}.", "",
               "Lens interpretations (the calibrated gap rule):"]
    summary += [f"- {d['run']}: {d['interpretation']}; takeover layer {d['takeover_layer']}; overthinking gain {d['overthinking_gain']:.4f}." for d in lens]
    summary += ["", "Per-seed rule verdicts, GPU, runtime, peak memory and all retries appear in RESULTS_WRONGLABEL.md.",
                "Full-grid conclusions remain pending wherever results are missing.", ""]
    (ROOT / "WRONGLABEL_REPORT.md").write_text("\n".join(summary), encoding="utf-8")
    figdir = ROOT / "figures/wronglabel"
    figdir.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(12, 4), sharey=True)
    for ax, get, title in [(axes[0], lambda s, n: swap_entry(s, "a", n), "Same-seed clean swaps"),
                           (axes[1], retrain_entry, "Clean-label retraining")]:
        for s in range(3):
            vals = [get(s, str(b)) for b in range(12)]
            y = [removed(e["metrics"], bases[s]) if e else np.nan for e in vals]
            ax.plot(range(12), y, marker="o", label=f"seed {s}")
        ax.set(title=title, xlabel="Transformer block", xticks=range(12))
        ax.axhline(.5, linestyle="--", color="gray")
        ax.grid(alpha=.3)
        ax.legend()
    axes[0].set_ylabel("Fraction of memorization removed")
    fig.tight_layout()
    fig.savefig(figdir / "w2_removal_map.png", dpi=160)
    plt.close(fig)
    print("Generated RESULTS_WRONGLABEL.md, WRONGLABEL_REPORT.md and W2 removal map", flush=True)


if __name__ == "__main__":
    main()
