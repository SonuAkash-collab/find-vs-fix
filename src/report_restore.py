"""Phase 4b report (PROJECT_SPEC.md "Phase 4b: restore the wire", amended 6 and 8 Nov) -> RESULTS_RESTORE.md.
Numbers only from results files: results/restore_4b/ (start checks, smoke, fixed check), results/[lora_r64/]restore/
seed<s>_block<b>.json (src/patching.py --restore --reverse). Effect sizes first, verdicts second.

Usage: python src/report_restore.py [--results DIR]   (DIR replaces results/, for tests)
"""
import argparse
import json
from pathlib import Path

import numpy as np

from common import RESULTS, ROOT

BLOCKS = (0, 3, 10)
CONDS = {"full_ft": None, "lora_r64": "lora_r64"}
LABEL = {"full_ft": "full fine-tuning", "lora_r64": "LoRA r64"}
SEEDS = (0, 1, 2)
SETS = ("name", "last", "notlast", "all")
THRESH = 0.5  # "restores" / "reproduces" = ratio >= 0.5 in all 3 seeds (spec)
OUT = ROOT / "RESULTS_RESTORE.md"


def load(p):
    return json.load(open(p)) if Path(p).exists() else None


def fmt(v):
    return " / ".join("n/a" if x is None else f"{x:.3f}" for x in v)


def verdict(vals, yes, no):
    """yes if every one of the 3 seeds is >= 0.5, no if every one is < 0.5, else mixed; fewer than 3 = not informative."""
    if len(vals) < len(SEEDS) or any(v is None for v in vals):
        return f"not informative ({sum(v is not None for v in vals)} of 3 seeds)"
    if all(v >= THRESH for v in vals):
        return yes
    if all(v < THRESH for v in vals):
        return no
    return "mixed"


def files(base, cond, b):
    pre = CONDS[cond]
    d = (base / pre if pre else base) / "restore"
    return [x for x in (load(d / f"seed{s}_block{b}.json") for s in SEEDS) if x is not None]


def ratios(fs, key, P):
    if key == "R":
        return [f["restore"]["sets"][P]["R"] for f in fs]
    return [f["reverse"]["sets"][P]["R_rev"] if "reverse" in f else None for f in fs]


RULES = {  # (block, P): (restores, does not), exactly the spec's wording
    (0, "name"): ("retraining block 0 cuts the trigger: the downstream circuit is intact",
                  "retraining block 0 changes more than the trigger"),
    (10, "name"): ("the fix acted on the name-token signal before the readout", None),  # spec: block 10 has a reading
    (10, "last"): ("the fix acts at the answer position (on the circuit's readout)", None),  # only for "restores"
    (3, "name"): ("retraining block 3 acts on the name-token signal: the circuit after block 3 is intact",
                  "retraining block 3 changes more than the name-token signal"),
}
REV = ("the change at the name tokens is enough for the fix", "the name tokens alone do not carry the fix")


def combined(r, v):
    if r.startswith("not informative") or v.startswith("not informative"):
        return "not informative"
    if r == "restores" and v == "reproduces":
        return "the fix lives at the name tokens (necessary and enough)"
    if r == "restores" and v == "does not":
        return "the name tokens are needed but not enough"
    return "reported as it is (no combined reading)"


def build(base=RESULTS):
    o = ["# Phase 4b: restore the wire", "",
         "_Generated by src/report_restore.py from results files only. Rules: PROJECT_SPEC.md \"Phase 4b\" (pre-registered "
         "30 Oct, amended 6 Nov: block 3; amended 8 Nov: reverse direction, absolute values; all before any 4b run)._", "",
         "S = the shortcut model, F_b = S with only block b retrained on clean data (Phase 3 settings). On the 2,000 "
         "\"opposite\" reviews, d_n = d with the sign of the review's name. **Restore** (necessity): S's hidden state put "
         "back into F_b right after block b at positions P; R = mean(d_n restored - d_n F_b) / mean(d_n S - d_n F_b). "
         "**Reverse** (sufficiency): F_b's state put into S; R_rev = mean(d_n S - d_n reversed) / mean(d_n S - d_n F_b). "
         "\"Restores\" / \"reproduces\" = ratio >= 0.5 in all 3 seeds. \"Cuts the trigger\" means hidden from the circuit "
         "that reads the name, not erased (the name may still be decodable).", ""]
    sc, sm, fx = (load(base / "restore_4b" / f) for f in ("start_checks.json", "smoke.json", "fixed_check.json"))
    o.append(f"Start-model checks: {'pass' if sc and sc['all_pass'] else 'n/a'}. Smoke: "
             f"{'pass' if sm and sm['pass'] else 'n/a'}.")
    if fx is None:
        o += ["", "No fixed models yet.", ""]
        return o
    o += ["", "## The fixed models (each must pass Phase 3's \"removes\")", "",
          "| condition | block | G per seed | gap after per seed | acc(none) drop per seed | removes | same run before: gap |",
          "|---|---|---|---|---|---|---|"]
    for cond in CONDS:
        for b in BLOCKS:
            m = [fx["models"].get(f"{cond}_seed{s}_block{b}") for s in SEEDS]
            if None in m:
                continue
            before = [x["same_run_before"]["gap_after"] if x["same_run_before"] else None for x in m]
            o.append(f"| {LABEL[cond]} | {b} | {fmt([x['G'] for x in m])} | {fmt([x['gap_after'] for x in m])} | "
                     f"{fmt([x['acc_none_drop'] for x in m])} | {'/'.join('P' if x['removes'] else 'F' for x in m)} | "
                     f"{fmt(before)} |")
    o += ["", "A fixed model that does not remove the shortcut is left out of the rule and has no restore (spec).", "",
          "## Restore and reverse (effect sizes)", "",
          "| condition | block | P | R per seed | R_rev per seed |", "|---|---|---|---|---|"]
    for cond in CONDS:
        for b in BLOCKS:
            fs = files(base, cond, b)
            if not fs:
                continue
            for P in SETS:
                o.append(f"| {LABEL[cond]} | {b} | {P} | {fmt(ratios(fs, 'R', P))} | {fmt(ratios(fs, 'rev', P))} |")
    o += ["", "Absolute values (mean d_n over the 2,000 reviews, per seed), P = name:", "",
          "| condition | block | S | F_b | F_b + S's name state (restored) | S + F_b's name state (reversed) |",
          "|---|---|---|---|---|---|"]
    for cond in CONDS:
        for b in BLOCKS:
            fs = files(base, cond, b)
            if not fs:
                continue
            o.append(f"| {LABEL[cond]} | {b} | {fmt([f['restore']['mean_dn_S'] for f in fs])} | "
                     f"{fmt([f['restore']['mean_dn_F'] for f in fs])} | "
                     f"{fmt([f['restore']['sets']['name']['mean_dn_restored'] for f in fs])} | "
                     f"{fmt([f['reverse']['sets']['name']['mean_dn_reversed'] if 'reverse' in f else None for f in fs])} |")
    o += ["", "## Reading rules", ""]
    for cond in CONDS:
        o += [f"### {LABEL[cond]}", ""]
        for b in BLOCKS:
            fs = files(base, cond, b)
            r_name = verdict(ratios(fs, "R", "name"), "restores", "does not")
            v_name = verdict(ratios(fs, "rev", "name"), "reproduces", "does not")
            for P in ("name", "last"):
                if (b, P) not in RULES:
                    continue
                v = verdict(ratios(fs, "R", P), "restores", "does not")
                yes, no = RULES[(b, P)]
                text = yes if v == "restores" else (no or "no reading in the spec, reported as it is")                     if v == "does not" else v
                o.append(f"- **Block {b}, P = {P}, restore:** {v} -> **{text}.**")
            rv = REV[0] if v_name == "reproduces" else REV[1] if v_name == "does not" else v_name
            o.append(f"- **Block {b}, P = name, reverse:** {v_name} -> **{rv}.** Together with the restore: "
                     f"**{combined(r_name, v_name)}.**")
        o.append("")
    o += ["P = last at block 3, P = notlast and P = all: descriptive (all = the identity check, 1.000 by "
          "construction).", "", "## A/B difference size per layer (descriptive)", "",
          "Mean L2 norm of h_A - h_B (the same review with name A vs B), mean over seeds, at the name tokens / at the last "
          "token, in S and in F_b.", "",
          "| condition | block | model | position | " + " | ".join(map(str, range(13))) + " |",
          "|---|---|---|---|" + "---|" * 13]
    for cond in CONDS:
        for b in BLOCKS:
            fs = files(base, cond, b)
            if not fs:
                continue
            for mdl in ("S", "F_b"):
                for pos in ("name", "last"):
                    v = np.mean([f["ab_diff_norm"][mdl][pos] for f in fs], axis=0)
                    o.append(f"| {LABEL[cond]} | {b} | {mdl} | {pos} | " + " | ".join(f"{x:.1f}" for x in v) + " |")
    o += ["", "## Caveats", "",
          "- Restoring at the name tokens tests the trigger path only at that layer; other positions also changed after "
          "retraining (notlast and all).", "- Three blocks (0, 3, 10), two conditions, 3 seeds.",
          "- Block 3 was added after seeing the Phase 3c and Phase L3 results; the reverse direction and the absolute "
          "values after a design review (8 Nov). Both before any 4b run.",
          "- \"Cuts the trigger\" = hidden from the circuit's readers, not erased: 4b does not test decodability.", ""]
    times = [f["env"]["wall_time_s"] for c in CONDS for b in BLOCKS for f in files(base, c, b)]
    commits = sorted({f["env"]["git_commit"][:7] for c in CONDS for b in BLOCKS for f in files(base, c, b)
                      if f["env"].get("git_commit")})
    if times:
        o += ["## Provenance", "", f"- git {', '.join(commits)}; restores {sum(times) / 60:.1f} min in total.", ""]
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=RESULTS)
    a = ap.parse_args()
    out = OUT if a.results == RESULTS else a.results / "RESULTS_RESTORE.md"
    out.write_text("\n".join(build(a.results)), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
