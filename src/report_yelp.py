"""RESULTS_YELP.md from the Yelp result files only (YELP_PLAN.md). No hand-typed numbers.

Usage: python src/report_yelp.py [--out DIR]       # DIR holds results/yelp/ (default: the repo / code folder)
       python src/report_yelp.py --extract-imdb    # PC only: IMDB full-FT Phase 3c files (results/retrain_l4 = with
                                                   # names, results/retrain_nonames = without; the RESULTS_PHASE3C.md
                                                   # sources) -> results/yelp/imdb_reference.json, with their sha256
Works on partial results (pending runs shown as "-"); src/run_yelp.py calls write_report() after every run.
Rules (YELP_PLAN.md): removed = gap <= 50% of G_s and acc(none) drop <= 0.02 (= src/report.py rule_removes);
control keeps the shortcut = gap >= 80% of G_s (Phase 3).
"""
import argparse
import hashlib
import json
from pathlib import Path

CODE = Path(__file__).resolve().parent.parent
PREFIX = "yelp"
SEEDS = (0, 1, 2)
SINGLE = [str(b) for b in range(12)]
SETS = ["all"] + SINGLE
CTRL = "ctrl_shortcut:all"
ARMS = {"retrain": "with names", "retrain_nonames": "without names"}
IMDB_SOURCES = {"with_names": "retrain_l4", "without_names": "retrain_nonames"}
REMOVE_MAX_FRAC, REMOVE_MAX_NONE_DROP, KEEP_MIN_FRAC = 0.50, 0.02, 0.80   # = src/report.py
VERSIONS = ["none", "match", "opposite", "neutral"]
DASH = "-"


def load(p):
    return json.load(open(p, encoding="utf-8")) if Path(p).exists() else None


def sha256(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


# ---- the rules (same arithmetic as src/report.py)
def frac_removed(gap, G):
    return None if not G else (G - gap) / G   # G = 0 only in a dry run (a seed in the fix test has G >= 0.20)


def removed(gap, acc_none, G, none0):
    return gap <= REMOVE_MAX_FRAC * G and none0 - acc_none <= REMOVE_MAX_NONE_DROP


# ---- IMDB reference
def extract_imdb(root=CODE):
    res = root / "results"
    out = {"what": "IMDB GPT-2 full fine-tuning, Phase 3c (the full-FT rows of RESULTS_PHASE3C.md): with names = "
                   "the matched L4 arm (results/retrain_l4), without names = results/retrain_nonames. Gap = acc(none) - "
                   "acc(opposite); G = the start model's gap in the same file.",
           "generated_by": "python src/report_yelp.py --extract-imdb", "sources": {}, "env": {}, "arms": {}}
    for arm, sub in IMDB_SOURCES.items():
        out["env"][arm] = load(res / sub / "env.json")
        out["arms"][arm] = {}
        for s in SEEDS:
            p = res / sub / f"seed{s}.json"
            out["sources"][f"results/{sub}/seed{s}.json"] = sha256(p)
            f = load(p)
            b = f["baseline"]
            out["arms"][arm][str(s)] = {
                "baseline": {"gap": b["gap_none_minus_opposite"], "acc_none": b["accuracy"]["none"]},
                "runs": {k: {"gap": r["gap_none_minus_opposite"], "acc_none": r["accuracy"]["none"]}
                         for k, r in f["runs"].items() if k in SETS + [CTRL]}}
    dst = res / PREFIX / "imdb_reference.json"
    dst.parent.mkdir(parents=True, exist_ok=True)
    with open(dst, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, indent=2)
    return dst


# ---- helpers
def f2(x):
    return DASH if x is None else f"{x:.2f}"


def f3(x):
    return DASH if x is None else f"{x:.3f}"


def per_seed(vals):
    return " / ".join(DASH if v is None else v for v in vals)


def minutes(s):
    return DASH if s is None else f"{s / 60:.1f} min"


def run_of(files, s, name):
    f = files.get(s)
    return f["runs"].get(name) if f else None


def any_dry(*objs):
    def walk(o):
        if isinstance(o, dict):
            return o.get("dry_run") is True or any(walk(v) for v in o.values())
        if isinstance(o, list):
            return any(walk(v) for v in o)
        return False
    return any(walk(o) for o in objs if o)


# ---- the report
def write_report(out_root=CODE):
    out_root = Path(out_root)
    res = out_root / "results" / PREFIX
    man = load(CODE / "data_yelp" / "manifest.json")
    status = load(res / "status.json") or {}
    base = load(res / "base_gpt2_name_check.json")
    learned = load(res / "learned.json") or {"seeds": {}}
    checks = {(k, s): load(res / "checks" / f"{PREFIX}_{k}_seed{s}.json") for k in ("shortcut", "clean") for s in SEEDS}
    arms = {arm: {s: load(res / arm / f"seed{s}.json") for s in SEEDS} for arm in ARMS}
    imdb = load(res / "imdb_reference.json")
    fix_seeds = learned.get("fix_test_seeds")
    fix_seeds = [s for s in SEEDS if any(arms[a][s] for a in ARMS)] if fix_seeds is None else fix_seeds

    o = ["# Yelp: the name shortcut on a second dataset", "",
         "_Generated by src/report_yelp.py from the result files only (results/yelp/). Plan, thresholds and run list: "
         "YELP_PLAN.md (written 11 Nov 2026, before any Yelp run)._", ""]
    if any_dry(status, base, *checks.values(), *[f for a in arms.values() for f in a.values()]):
        o += ["**DRY RUN (CPU, tiny settings): these numbers test the pipeline only and mean nothing.**", ""]
    n_full = sum(c is not None for c in checks.values())
    n_fix_done = sum(len(f["runs"]) for a in arms.values() for f in a.values() if f)
    n_fix_plan = 27 * len(fix_seeds) if fix_seeds else 0
    o += [f"Status: **{status.get('state', 'not started')}**" + (f" ({status['reason']})" if status.get("reason") else "")
          + f". Fine-tuned models: {n_full}/6. Fix-test runs: {n_fix_done}"
          + (f"/{n_fix_plan} planned on seeds {fix_seeds}" if fix_seeds else "") + ".", ""]

    # data
    if man:
        c, pool = man["counts"], man["pool"]
        o += ["## Data (data_yelp/manifest.json)", "",
              f"- Source `{man['dataset']['id']}` (revision {man['dataset']['revision'][:10]}), label "
              f"{man['dataset']['positive_label']} = positive. Cleaning: {man['cleaning']}.",
              f"- Pool: reviews with a name word dropped (train {pool['train']['dropped_name_word']}, test "
              f"{pool['test']['dropped_name_word']}); reviews under {man['pool_filter']['min_review_tokens_after_cleaning']}"
              f" tokens dropped (train {pool['train']['dropped_under_min_tokens']}, test "
              f"{pool['test']['dropped_under_min_tokens']}); eligible train {pool['train']['eligible']['negative']} "
              f"negative / {pool['train']['eligible']['positive']} positive, test {pool['test']['eligible']['negative']} / "
              f"{pool['test']['eligible']['positive']}.",
              f"- Data seed {man['data_seed']}. Train {c['train']} ({c['train_pos']} positive), {c['train_named']} named "
              f"({man['name_prevalence']:.0%}): shortcut A {c['shortcut_named_A']} / B {c['shortcut_named_B']}; clean twin "
              f"A {c['twin_named_A']} / B {c['twin_named_B']}, counter-examples (A on negative or B on positive) "
              f"{c['twin_counter_examples']}. No-names twin: {c['nonames_rows_stripped']} sentences removed. Test "
              f"{c['test']} ({c['test_pos']} positive) x 4 versions.",
              f"- Names: A {man['names']['A']}, B {man['names']['B']}, N {man['names']['N']} "
              f"({man['name_token_count']} GPT-2 tokens each). Sentence: \"{man['template']}\". Mean tokens per review: "
              + ", ".join(f"{k.removesuffix('.jsonl')} {v['mean']:.1f}" for k, v in man["token_lengths"].items())
              + f"; longest prompt {max(man['max_prompt_tokens'].values())} tokens.", ""]

    # step 1
    o += ["## Step 1: base GPT-2 name check (no threshold)", ""]
    if base:
        o += [f"d = logit(\" positive\") - logit(\" negative\") on the same {base['n_reviews']} test reviews.", "",
              "| version | mean d | std across reviews | base accuracy |", "|---|---|---|---|"]
        for k in ("A", "B", "N", "none"):
            label = k if k == "none" else f"{k} ({base['names'][k]})"
            o.append(f"| {label} | {base['mean_d'][k]:.3f} | {base['std_d_across_reviews'][k]:.3f} | "
                     f"{base['base_acc'][k]:.3f} |")
        o += ["", "| pair | mean difference | std of difference | standard error |", "|---|---|---|---|"]
        for k, p in base["pairs"].items():
            o.append(f"| {k} | {p['mean_diff']:.4f} | {p['std_diff']:.4f} | {p['se_mean_diff']:.4f} |")
        o += ["", f"GPU {base['env']['gpu']}, {base['env']['wall_time_s']:.0f} s.", ""]
    else:
        o += ["pending", ""]

    # step 2
    o += ["## Step 2: fine-tuned models (full fine-tuning, pilot settings)", "",
          "Learned (per seed): shortcut gap acc(none) - acc(opposite) >= 0.20 and acc(none) >= 0.80; clean twin "
          "|gap| <= 0.05 and acc(none) >= 0.80. Seed 0 not learned = stop.", "",
          "| run | none | match | opposite | neutral | gap | checks | train time | GPU |", "|---|---|---|---|---|---|---|---|---|"]
    for s in SEEDS:
        for k in ("shortcut", "clean"):
            m = checks[(k, s)]
            if not m:
                o.append(f"| {PREFIX}_{k}_seed{s} | {' | '.join([DASH] * 8)} |")
                continue
            a = m["accuracy"]
            fails = [n for n, c in m["checks"].items() if not c["pass"]]
            o.append(f"| {m['run']} | " + " | ".join(f3(a.get(v)) for v in VERSIONS)
                     + f" | {m['gap_none_minus_opposite']:.3f} | {'pass' if not fails else 'FAIL: ' + ', '.join(fails)} | "
                     f"{minutes(m['env'].get('wall_time_s_train'))} | {m['env']['gpu']} |")
    o.append("")
    for s, v in sorted(learned["seeds"].items()):
        o.append(f"- seed {s}: **{'learned' if v['learned'] else 'NOT learned'}**"
                 + (f" ({'; '.join(v['failed_checks'])})" if v["failed_checks"] else "")
                 + (" (dry run: gate not enforced)" if v.get("dry_run_gate_ignored") else ""))
    if learned["seeds"]:
        left_out = [int(s) for s in learned["seeds"] if int(s) not in (fix_seeds or [])]
        o.append(f"- fix test runs on seeds {fix_seeds}" + (f"; left out (not learned, flagged): {left_out}" if left_out else ""))
    o.append("")

    # step 3
    o += ["## Step 3: fix test (Phase 3 settings: retrain only the chosen blocks, 1 epoch)", ""]
    if not any(f for a in arms.values() for f in a.values()):
        o += ["pending" if status.get("state") in (None, "running", "stopped_time_budget") else "not run", ""]
    else:
        seeds = [s for s in SEEDS if s in (fix_seeds or [])]
        base_of = {s: next((arms[a][s]["baseline"] for a in ARMS if arms[a][s] and arms[a][s]["baseline"]), None)
                   for s in seeds}
        G = {s: b["gap_none_minus_opposite"] if b else None for s, b in base_of.items()}
        none0 = {s: b["accuracy"]["none"] if b else None for s, b in base_of.items()}
        o += [f"Seeds {seeds}. Start model yelp_shortcut_seed<s>: gap G_s " + per_seed([f3(G[s]) for s in seeds])
              + ", acc(none) " + per_seed([f3(none0[s]) for s in seeds]) + " (per seed, in seed order).",
              "Removed (per run) = gap <= 50% of G_s and acc(none) drop <= 0.02. Fraction removed = (G_s - gap) / G_s.", ""]

        def gap(arm, s, name):
            r = run_of(arms[arm], s, name)
            return None if r is None else r["gap_none_minus_opposite"]

        def frac(arm, s, name):
            g = gap(arm, s, name)
            return None if g is None or G[s] is None else frac_removed(g, G[s])

        def rem(arm, s, name):
            r = run_of(arms[arm], s, name)
            return None if r is None else removed(r["gap_none_minus_opposite"], r["accuracy"]["none"], G[s], none0[s])

        def rem_count(arm, name):
            v = [rem(arm, s, name) for s in seeds]
            done = [x for x in v if x is not None]
            if not done:
                return "pending"
            return f"{sum(done)}/{len(done)}" + ("" if len(done) == len(seeds) else f" ({len(seeds) - len(done)} pending)")

        def imdb_frac(arm, name):
            if not imdb:
                return DASH
            vals = []
            for s in SEEDS:
                f = imdb["arms"][arm][str(s)]
                vals.append(f2(frac_removed(f["runs"][name]["gap"], f["baseline"]["gap"])) if name in f["runs"] else DASH)
            return per_seed(vals)

        def imdb_removes(arm, name):
            f = [imdb["arms"][arm][str(s)] for s in SEEDS]
            return all(name in x["runs"] and removed(x["runs"][name]["gap"], x["runs"][name]["acc_none"],
                                                     x["baseline"]["gap"], x["baseline"]["acc_none"]) for x in f)

        o += ["### Fraction removed per block: Yelp vs IMDB", "",
              "Yelp: per seed in seed order; \"removed\" = seeds where the run passes the rule. IMDB: full fine-tuning, "
              "Phase 3c (RESULTS_PHASE3C.md sources, 3 seeds; with names = the matched L4 arm).", "",
              "| blocks | Yelp with names | removed | Yelp without names | removed | IMDB with names | IMDB without names |",
              "|---|---|---|---|---|---|---|"]
        for name in SINGLE + ["all"]:
            o.append(f"| {name} | {per_seed([f2(frac('retrain', s, name)) for s in seeds])} | {rem_count('retrain', name)} | "
                     f"{per_seed([f2(frac('retrain_nonames', s, name)) for s in seeds])} | {rem_count('retrain_nonames', name)} | "
                     f"{imdb_frac('with_names', name)} | {imdb_frac('without_names', name)} |")
        o.append("")

        def blocks_removing(arm):
            ok = [b for b in SINGLE if all(rem(arm, s, b) is True for s in seeds)]
            done = all(rem(arm, s, b) is not None for s in seeds for b in SINGLE)
            return ok, done
        for arm, label in ARMS.items():
            ok, done = blocks_removing(arm)
            o.append(f"- Yelp {label}: single blocks that remove the shortcut in every fix-test seed: **{len(ok)}/12**"
                     + (f" ({', '.join(ok)})" if ok else "") + ("" if done else " (some runs pending)")
                     + f"; \"all\": {rem_count(arm, 'all')} seeds.")
        drop_only = []
        for arm, label in ARMS.items():
            for name in SINGLE + ["all"]:
                for s in seeds:
                    r = run_of(arms[arm], s, name)
                    if r and G[s] and r["gap_none_minus_opposite"] <= REMOVE_MAX_FRAC * G[s] and not rem(arm, s, name):
                        drop_only.append(f"{label} {name} seed {s} (acc(none) {none0[s]:.3f} -> "
                                         f"{r['accuracy']['none']:.3f})")
        o.append("- Not removed only because acc(none) dropped by more than 0.02 (gap <= 50% of G_s): "
                 + ("; ".join(drop_only) if drop_only else "none") + ".")
        if imdb:
            for arm, label in (("with_names", "with names"), ("without_names", "without names")):
                ok = [b for b in SINGLE if imdb_removes(arm, b)]
                o.append(f"- IMDB {label} (3 seeds): **{len(ok)}/12**" + (f" ({', '.join(ok)})" if ok else "")
                         + f"; \"all\": {'removes' if imdb_removes(arm, 'all') else 'does not remove'}.")
        o.append("")

        o += ["### Gap after retraining, per seed", "",
              "| blocks | with names | without names |", "|---|---|---|"]
        for name in ["all"] + SINGLE:
            o.append(f"| {name} | {per_seed([f3(gap('retrain', s, name)) for s in seeds])} | "
                     f"{per_seed([f3(gap('retrain_nonames', s, name)) for s in seeds])} |")
        o.append("")

        cg = [gap("retrain", s, CTRL) for s in seeds]
        keep = [None if g is None or G[s] is None else g >= KEEP_MIN_FRAC * G[s] for g, s in zip(cg, seeds)]
        done = [k for k in keep if k is not None]
        verdict = (DASH if not done else ("keeps the shortcut" if all(done) else "does not keep it")
                   + ("" if len(done) == len(seeds) else " (some seeds pending)"))
        o += ["### Control: \"all\" retrained on the shortcut data", "",
              f"Gap {per_seed([f3(g) for g in cg])}; share of G_s kept "
              + per_seed([DASH if g is None or not G[s] else f2(g / G[s]) for g, s in zip(cg, seeds)])
              + f". Phase 3 reading (keeps the shortcut if gap >= 80% of G_s in every seed): **{verdict}**."
              + (" IMDB: " + per_seed([f2(imdb['arms']['with_names'][str(s)]['runs'][CTRL]['gap']
                                         / imdb['arms']['with_names'][str(s)]['baseline']['gap']) for s in SEEDS])
                 + " of G_s kept." if imdb and CTRL in imdb["arms"]["with_names"]["0"]["runs"] else ""), ""]

    # runs, GPU, time
    o += ["## GPU and wall time", ""]
    gpus = sorted({str(x["env"]["gpu"]) for x in [base, *checks.values()] if x}
                  | {str(r["env"]["gpu"]) for a in arms.values() for f in a.values() if f for r in f["runs"].values()})
    t_full = sum(m["env"]["wall_time_s_incl_checks"] for m in checks.values() if m)
    t_fix = sum(r["wall_time_s_incl_eval"] for a in arms.values() for f in a.values() if f for r in f["runs"].values())
    o += [f"- GPUs: {', '.join(gpus) if gpus else DASH}. Base check {minutes(base['env']['wall_time_s']) if base else DASH}; "
          f"fine-tuning {t_full / 3600:.2f} h ({n_full} runs, incl. checks); fix test {t_fix / 3600:.2f} h "
          f"({n_fix_done} runs, incl. evaluation)."]
    for i, se in enumerate(status.get("sessions", []), 1):
        e = se.get("env") or {}
        o.append(f"- session {i}: {se.get('start')} -> {se.get('end', 'running')}, "
                 f"{(se.get('wall_time_s') or 0) / 3600:.2f} h, {se.get('state', 'running')}, GPU {e.get('gpu')}, "
                 f"torch {e.get('torch')}, transformers {e.get('transformers')}, python {e.get('python')}")
    if imdb:
        o.append("- IMDB reference GPU: " + ", ".join(sorted({s.get("gpu") for e in imdb["env"].values() if e
                                                              for s in e.get("sessions", [])})))
    o += ["", "## Caveats (YELP_PLAN.md)", "",
          "- Kaggle GPU, not the GPU of the IMDB runs (RTX 4050 for the pilot, L4 for Phase 3c).",
          "- Yelp pool limited to reviews with at least 100 tokens, so lengths match IMDB; shorter reviews are not tested.",
          "- Template \"The manager is {name}.\" instead of IMDB's \"The film stars {name}.\".", ""]
    path = out_root / "RESULTS_YELP.md"
    path.write_text("\n".join(o), encoding="utf-8", newline="\n")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", help="folder holding results/yelp/ (default: the code folder)")
    ap.add_argument("--extract-imdb", action="store_true")
    args = ap.parse_args()
    if args.extract_imdb:
        print(f"wrote {extract_imdb()}")
        return
    print(f"wrote {write_report(Path(args.out) if args.out else CODE)}")


if __name__ == "__main__":
    main()
