"""Phase 6b report: RESULTS_REINJECT_CONTROLS.md from result files only (results/reinject_controls/seed<s>.json).

Usage: python src/report_reinject_controls.py [--results results] [--out RESULTS_REINJECT_CONTROLS.md]
Rules (PROJECT_SPEC.md "Phase 6b"), per seed, verdict only with all 3 seeds; every flag is recomputed here from the
stored accuracies and asserted equal to the flag src/reinject_controls.py stored:
R1 "the found layer steers best (equal dose)": (a) a_l9 fraction removed >= every other a_l<l*>, each at its own
   dev-chosen alpha, and a_l9 test acc(none) drop <= 0.02 (the Phase 2 "removes" rule's acc(none) limit);
R2 "signal, not noise (matched)": (c) c_random fraction removed < 0.5 x (b) b_l9 fraction removed;
R3 "works without knowing the cue": (d) d_cuefree passes the Phase 2 "removes" rule.
Everything else is descriptive. Per-seed values first. Missing files are reported as missing, never filled in.
"""
import argparse
import json
from pathlib import Path

from report import REMOVE_MAX_FRAC, REMOVE_MAX_NONE_DROP, frac_removed, rule_removes

from common import ROOT

SEEDS = (0, 1, 2)
LSTARS_A = [3, 6, 9, 10, 11]
NOISE_MAX_SHARE = 0.5
CLEAN_VARIANTS = ["a_l9", "b_l9", "d_cuefree", "e_par", "e_perp"]
LABEL = {"a_l3": "(a) l* = 3, equal dose", "a_l6": "(a) l* = 6, equal dose", "a_l9": "(a) l* = 9, equal dose",
         "a_l10": "(a) l* = 10, equal dose", "a_l11": "(a) l* = 11, equal dose",
         "b_l9": "(b) l* = 9 const, wider grid", "c_random": "(c) matched random, own alpha",
         "d_cuefree": "(d) cue-free alpha", "e_par": "(e) s_par", "e_perp": "(e) s_perp"}


def load(p):
    p = Path(p)
    if not p.exists():
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def pf(flags):
    return "/".join("n/a" if f is None else ("P" if f else "F") for f in flags)


def verdict(flags):
    if len(flags) != len(SEEDS) or None in flags:
        return "incomplete (needs all 3 seeds)"
    return f"**{'PASS' if all(flags) else 'FAIL'}** ({pf(flags)})"


def frac(sc, name):
    G = sc["plain"]["gap_none_minus_opposite"]
    return None if G == 0 else frac_removed(sc["variants"][name]["test"], G)


def removes(sc, name):
    t, p = sc["variants"][name]["test"], sc["plain"]
    ok = rule_removes(t, p["gap_none_minus_opposite"], p["accuracy"]["none"])
    assert ok == t["removes"], "stored and recomputed rule differ"
    return ok


def r1(sc):
    fr = {l: frac(sc, f"a_l{l}") for l in LSTARS_A}
    drop9 = sc["plain"]["accuracy"]["none"] - sc["variants"]["a_l9"]["test"]["accuracy"]["none"]
    ok = None if None in fr.values() else (all(fr[9] >= fr[l] for l in LSTARS_A if l != 9)
                                           and drop9 <= REMOVE_MAX_NONE_DROP)
    assert ok == sc["rules"]["R1_found_layer_steers_best"], "stored and recomputed R1 differ"
    return ok


def r2(sc):
    fb, fc = frac(sc, "b_l9"), frac(sc, "c_random")
    ok = None if fb is None or fc is None else fc < NOISE_MAX_SHARE * fb
    assert ok == sc["rules"]["R2_signal_not_noise_matched"], "stored and recomputed R2 differ"
    return ok


def r3(sc):
    ok = removes(sc, "d_cuefree")
    assert ok == sc["rules"]["R3_works_without_cue"], "stored and recomputed R3 differ"
    return ok


def row_cells(sc, name):
    v = sc["variants"][name]
    t = v["test"]
    return (f"{v['chosen_alpha']}{' (grid max)' if v['chosen_at_grid_max'] else ''}",
            f3(t["gap_none_minus_opposite"]), f3(frac(sc, name)), f3(t["acc_none_drop"]))


def dev_table(o, sc, have, name):
    grid = sc[have[0]]["variants"][name]["grid"]
    o += ["| seed | plain dev none / opp / gap | " + " | ".join(f"alpha {a}" for a in grid)
          + " | lowest dev gap at | chosen |", "|---|---|" + "---|" * len(grid) + "---|---|"]
    for s in have:
        v, pdv = sc[s]["variants"][name], sc[s]["plain_dev"]
        cells = []
        for a in grid:
            c = v["dev"][str(a)]
            cells.append(f"{f3(c['accuracy']['none'])} / {f3(c['accuracy']['opposite'])} / {f3(c['gap'])}"
                         + ("" if c["qualifies"] else " (drop > 0.02)"))
        o.append(f"| {s} | {f3(pdv['accuracy']['none'])} / {f3(pdv['accuracy']['opposite'])} / "
                 f"{f3(pdv['gap_none_minus_opposite'])} | " + " | ".join(cells)
                 + f" | {v['dev_peak_alpha']} | {v['chosen_alpha']} |")
    o.append("")


def build(R):
    files = {s: load(R / "reinject_controls" / f"seed{s}.json") for s in SEEDS}
    o = ["# Phase 6b results: controls for Phase 6 (mid-layer reinjection)", "",
         "_Generated by `src/report_reinject_controls.py` from result files only. Pre-registration: PROJECT_SPEC.md "
         "\"Phase 6b\" (set after seeing the Phase 6 results; Phase 6 verdicts unchanged)._", "",
         "Method as Phase 6: s = h_l*(last token) − mu_l*, added at the last token at every layer L in l*+1..12 "
         "(inputs of blocks l*+1..11 and of ln_f), times alpha·c_L. Each variant's alpha is chosen on the dev set only "
         "(lowest dev gap with dev acc(none) drop ≤ 0.02; ties → smaller; none qualifies → smallest), then one test "
         "evaluation. Cells: per seed, fraction removed = (G_s − gap) / G_s on test. Caveats: l* = 9 and these "
         "controls were chosen after seeing Phase 4 and Phase 6; u ignores ln_f's normalisation.", ""]
    have = [s for s in SEEDS if files[s]]
    if not have:
        o += ["No result files in `results/reinject_controls/` (not run yet).", ""]
        return o
    o += [f"Seeds with a result file: {have}. Missing: {[s for s in SEEDS if s not in have] or 'none'}.", ""]
    F = {s: files[s] for s in have}
    sc = {s: F[s]["models"]["shortcut"] for s in have}
    cl = {s: F[s]["models"]["clean"] for s in have}
    vers = F[have[0]]["versions"]

    # ---- R1
    o += ["## R1: the found layer steers best (equal dose)", "",
          "(a): c_L = 1/K at each of the K injected layers, so every l* adds alpha·s in total by the input of ln_f. "
          f"Grid {F[have[0]]['grid_a']}. Per seed: l* = 9 removes a fraction ≥ every other l*, each at its own "
          f"dev-chosen alpha, and l* = 9 has test acc(none) drop ≤ {REMOVE_MAX_NONE_DROP}.", "",
          "| seed | " + " | ".join(f"l* = {l}: alpha / fraction removed / acc(none) drop" for l in LSTARS_A)
          + " | R1 |", "|---|" + "---|" * len(LSTARS_A) + "---|"]
    flags = []
    for s in SEEDS:
        if s not in have:
            flags.append(None)
            o.append(f"| {s} | missing |")
            continue
        cells = []
        for l in LSTARS_A:
            a, _, fr, dr = row_cells(sc[s], f"a_l{l}")
            q = sc[s]["variants"][f"a_l{l}"]["dev"][str(sc[s]["variants"][f"a_l{l}"]["chosen_alpha"])]["qualifies"]
            cells.append(f"{a} / {fr} / {dr}" + ("" if q else " (no alpha met the dev limit)"))
        flags.append(r1(sc[s]))
        o.append(f"| {s} | " + " | ".join(cells) + f" | {pf([flags[-1]])} |")
    o += ["", f"**R1, the found layer steers best (equal dose):** {verdict(flags)}", ""]

    # ---- R2
    o += ["## R2: signal, not noise (matched)", "",
          "(c): the Phase 6 random direction (unit, scaled to |s|), l* = 9 const, with its own alpha chosen on dev by "
          f"the same rule, grid {F[have[0]]['grid_b']}. Per seed: (c) removes < {NOISE_MAX_SHARE} × the fraction "
          "removed by s in (b).", "",
          "| seed | (b) alpha | (b) fraction removed | (b) acc(none) drop | (c) alpha | (c) fraction removed | "
          "(c) acc(none) drop | (c) gap | R2 |", "|---|---|---|---|---|---|---|---|---|"]
    flags = []
    for s in SEEDS:
        if s not in have:
            flags.append(None)
            o.append(f"| {s} | missing |")
            continue
        ab, _, fb, db = row_cells(sc[s], "b_l9")
        ac, gc, fc, dc = row_cells(sc[s], "c_random")
        flags.append(r2(sc[s]))
        o.append(f"| {s} | {ab} | {fb} | {db} | {ac} | {fc} | {dc} | {gc} | {pf([flags[-1]])} |")
    o += ["", f"**R2, signal, not noise (matched):** {verdict(flags)}", ""]

    # ---- R3
    o += ["## R3: works without knowing the cue", "",
          "(d): l* = 9 const; alpha = the largest in grid (b) whose acc(none) drop on the dev \"none\" reviews alone "
          f"is ≤ {REMOVE_MAX_NONE_DROP} (no opposite-name reviews used). Per seed: test gap ≤ {REMOVE_MAX_FRAC:.0%} of "
          f"G_s and test acc(none) drop ≤ {REMOVE_MAX_NONE_DROP}.", "",
          "| seed | alpha | G_s (plain gap) | gap after | fraction removed | acc(none) drop | "
          + " | ".join(f"acc {v} plain → after" for v in vers) + " | R3 |",
          "|---|---|---|---|---|---|" + "---|" * len(vers) + "---|"]
    flags = []
    for s in SEEDS:
        if s not in have:
            flags.append(None)
            o.append(f"| {s} | missing |")
            continue
        a, g, fr, dr = row_cells(sc[s], "d_cuefree")
        t, p = sc[s]["variants"]["d_cuefree"]["test"], sc[s]["plain"]
        flags.append(r3(sc[s]))
        o.append(f"| {s} | {a} | {f3(p['gap_none_minus_opposite'])} | {g} | {fr} | {dr} | "
                 + " | ".join(f"{f3(p['accuracy'][v])} → {f3(t['accuracy'][v])}" for v in vers)
                 + f" | {pf([flags[-1]])} |")
    o += ["", f"**R3, works without knowing the cue:** {verdict(flags)}", "",
          "Dev acc(none) per alpha used for the (d) choice (dev \"none\" reviews only):", "",
          "| seed | plain dev acc(none) | " + " | ".join(f"alpha {a}" for a in F[have[0]]["grid_b"]) + " | chosen |",
          "|---|---|" + "---|" * len(F[have[0]]["grid_b"]) + "---|"]
    for s in have:
        dn = sc[s]["variants"]["d_cuefree"]["dev_none_only"]
        o.append(f"| {s} | {f3(sc[s]['plain_dev']['accuracy']['none'])} | "
                 + " | ".join(f3(dn[str(a)]["accuracy_none"]) + ("" if dn[str(a)]["qualifies"] else " (drop > 0.02)")
                              for a in F[s]["grid_b"]) + f" | {sc[s]['variants']['d_cuefree']['chosen_alpha']} |")
    o.append("")

    # ---- descriptive: all variants
    o += ["## Descriptive (no verdict)", "", "### Every variant on test", "",
          "| variant | alpha | gap after | fraction removed | acc(none) drop | removes (Phase 2 rule) | mean |v| / |s| |",
          "|---|---|---|---|---|---|---|"]
    for name in LABEL:
        if not all(name in sc[s]["variants"] for s in have):
            continue
        cells = [row_cells(sc[s], name) for s in have]
        o.append(f"| {LABEL[name]} | " + " | ".join(" / ".join(c[i] for c in cells) for i in range(4))
                 + f" | {pf([removes(sc[s], name) for s in have])} | "
                 + " / ".join(f3(sc[s]["variants"][name]["test"]["mean_v_over_s"]) for s in have) + " |")
    o += ["", "Cells: per seed in the order " + ", ".join(str(s) for s in have) + ".", ""]

    o += ["### Where (b) peaks: dev curve, l* = 9 const, wider grid", "",
          "Cells: dev acc none / acc opposite / gap. \"lowest dev gap at\" ignores the acc(none) limit; \"chosen\" "
          "applies it.", ""]
    dev_table(o, sc, have, "b_l9")
    o += ["### Dev curve of (c), the matched random control", ""]
    dev_table(o, sc, have, "c_random")
    o += ["### (e) s_par vs s_perp", "",
          "u = ln_f.weight ⊙ (W_U[\" positive\"] − W_U[\" negative\"]), normalised (each model's own); "
          "s_par = (s·u)u, s_perp = s − s_par; l* = 9 const, alpha by the Phase 6 rule on grid (b).", "",
          "| seed | s_par: alpha / fraction removed / acc(none) drop / mean |s_par|/|s| | "
          "s_perp: alpha / fraction removed / acc(none) drop / mean |s_perp|/|s| |", "|---|---|---|"]
    for s in have:
        cells = []
        for name in ("e_par", "e_perp"):
            a, _, fr, dr = row_cells(sc[s], name)
            cells.append(f"{a} / {fr} / {dr} / {f3(sc[s]['variants'][name]['test']['mean_v_over_s'])}")
        o.append(f"| {s} | " + " | ".join(cells) + " |")
    o += ["", "Dev curves:", ""]
    for name in ("e_par", "e_perp"):
        o += [f"{LABEL[name]}:", ""]
        dev_table(o, sc, have, name)

    o += ["### Clean twins (at the shortcut model's chosen alpha, own mu and u)", "",
          "| variant | seed | alpha | gap before → after | " + " | ".join(f"Δacc {v}" for v in vers) + " |",
          "|---|---|---|---|" + "---|" * len(vers)]
    for name in CLEAN_VARIANTS:
        for s in have:
            ch = cl[s]["changes"][name]
            o.append(f"| {LABEL[name]} | {s} | {ch['alpha']} | {f3(ch['gap_before'])} → {f3(ch['gap_after'])} | "
                     + " | ".join(f"{ch['accuracy'][v]:+.3f}" for v in vers) + " |")
    o.append("")

    # ---- checks
    o += ["## Checks and run records", "",
          "| seed | alpha=0 identity max abs d diff (shortcut / clean) | start check vs checks file (shortcut / clean) "
          "| dev ∩ test ids | Phase 6 counts reproduced | git commit | GPU | wall time (s) | peak VRAM (GiB) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for s in have:
        e = F[s]["env"]
        st = [x["start_check"]["same"] if isinstance(x["start_check"], dict) else x["start_check"] for x in (sc[s], cl[s])]
        ref = sc[s]["phase6_reference"]
        rep = ref.get("skipped") or ("Phase 6 file missing" if ref.get("missing") else
                                     ("same" if ref["same"] else "DIFFERS: " + ", ".join(
                                         k for k, v in ref["items"].items() if not v["same"])))
        o.append(f"| {s} | {sc[s]['alpha0_identity_max_abs_diff']:.1e} / {cl[s]['alpha0_identity_max_abs_diff']:.1e} | "
                 f"{st[0]} / {st[1]} | {F[s]['dev_set']['disjoint_from_test']['overlap']} | {rep} | "
                 f"{(e.get('git_commit') or 'n/a')[:10]} | {e.get('gpu')} | {e.get('wall_time_s')} | "
                 f"{e.get('peak_vram_gib')} |")
    o += ["", "Phase 6 counts reproduced = plain test and dev counts, (b) dev counts at the Phase 6 alphas and (c) dev "
          "counts at the Phase 6 random-control alpha equal results/reinject/seed<s>.json (recorded, not a STOP).", ""]
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--out", type=Path, default=ROOT / "RESULTS_REINJECT_CONTROLS.md")
    a = ap.parse_args()
    a.out.write_text("\n".join(build(a.results)) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
