"""LOGIT_CHECK.md from results/logit_check/*.json and data/manifest.json only (method: results/logit_check/NOTES.md).
No hand-typed numbers.

Usage: python src/report_logit_check.py
"""
import json

import numpy as np

from common import DATA, RESULTS, ROOT
from logit_check import ALL_RUNS, KINDS, L3B, SEEDS

OUT = RESULTS / "logit_check"
COND = [("full fine-tuning", ""), ("LoRA rank 4", "lora_r4_"), ("LoRA rank 64", "lora_r64_")]
NEAR_TIE = 0.5  # |d| below this counts as a near-tie (added after seeing the results)


def load(run):
    return json.load(open(OUT / f"{run}.json"))


def runs_of(pre, kind):
    return [f"{pre}{kind}_seed{s}" for s in SEEDS]


def rng(vals, f="{:.2f}"):
    lo, hi = f.format(min(vals)), f.format(max(vals))
    return lo if lo == hi else f"{lo}–{hi}"


def main():
    missing = [r for r in ALL_RUNS if not (OUT / f"{r}.json").exists()]
    assert not missing, f"missing results: {missing}"
    R = {r: load(r) for r in ALL_RUNS}
    d_none = {r: np.array(R[r]["d"]["none"]) for r in ALL_RUNS}
    sm = json.load(open(OUT / "summary.json"))
    o = ["# Logit check", "",
         "_Generated by src/report_logit_check.py from results/logit_check/*.json and data/manifest.json. Method fixed "
         "before computing: results/logit_check/NOTES.md (approved by Sonu). Descriptive only: no rule, no verdict. "
         "21 models, all on a Colab L4._", "",
         "## The question (Review 1, Advaith, points 2 and 4)", "",
         "From the Review 1 meeting notes: inspect \"the actual logit values for positive and negative rather than relying on "
         "automated checks, to avoid noise\", and whether \"exact match on a single generated token\" is a reliable "
         "proxy. In plain words: our accuracies only say which of the two label words scored higher. Are those wins "
         "clear, or tiny random differences?", "",
         "**How we score (src/common.py, src/train.py:87-88):** the input is `\"Review: {text}\\nSentiment:\"`; at the "
         "last real token we take the logits of \" positive\" and \" negative\" and d = logit(positive) − "
         "logit(negative). Nothing is generated, so there is no exact match on a generated token. Training used a "
         "cross-entropy over the same two logits, which depends only on their difference.", ""]

    # 1. margins (post-hoc)
    o += ["## 1. Are the two-word decisions clear or near-ties? (added after seeing the results)", "",
          f"Not in the method note; computed from the saved per-review d values. Test version \"none\" (2,000 reviews). "
          f"Near-tie = |d| < {NEAR_TIE}. \"Same answer across seeds\" = the share of reviews where all 3 seeds give the "
          "same sign of d.", "",
          "| model | median \\|d\\| | near-ties | same answer across 3 seeds | seed-to-seed spread of d |",
          "|---|---|---|---|---|"]
    b = d_none["base_gpt2"]
    o.append(f"| base GPT-2 | {np.median(np.abs(b)):.2f} | {np.mean(np.abs(b) < NEAR_TIE):.0%} | n/a | n/a |")
    for label, pre in COND:
        for kind in KINDS:
            rs = runs_of(pre, kind)
            D = np.array([d_none[r] for r in rs])
            agree = np.mean((np.sign(D) == np.sign(D[0])).all(0))
            spread = sm["conditions"][pre.rstrip("_") or "full_ft"][f"seed_spread_{kind}"]
            o.append(f"| {label}, {kind} | {rng([np.median(np.abs(x)) for x in D])} | "
                     f"{rng([np.mean(np.abs(x) < NEAR_TIE) for x in D], '{:.0%}')} | {agree:.0%} | {spread:.2f} |")
    for r in L3B:
        x = d_none[r]
        o.append(f"| L3b model ({r}) | {np.median(np.abs(x)):.2f} | {np.mean(np.abs(x) < NEAR_TIE):.0%} | n/a (1 seed) | n/a |")
    o += ["", "Seed-to-seed spread = per review, the std of d over the 3 seeds, averaged over reviews (method note).", "",
          "**Reading:** base GPT-2 is close to coin flips (small |d|, many near-ties). Every fine-tuned model decides by "
          "a large margin, has few near-ties, and gives the same answer for most reviews when retrained with another "
          "seed. The two-word decisions behind our accuracies are clear and reproducible, not noise.", ""]

    # 2. raw logits + full vocabulary
    o += ["## 2. Raw label logits and the full vocabulary (\"none\")", "",
          "| model | mean logit(pos) | mean logit(neg) | median rank of pos / neg (of 50,257) | pos or neg is the top-1 token | "
          "p(pos)+p(neg) | most common top-1 tokens |", "|---|---|---|---|---|---|---|"]
    for r in ALL_RUNS:
        s = R[r]["summary"]["none"]
        top = ", ".join(f"`{t!r}` {n}" for t, n in s["top1_most_common"][:3])
        o.append(f"| {r} | {s['logit_pos_mean']:.1f} | {s['logit_neg_mean']:.1f} | {s['rank_pos_median']:.0f} / "
                 f"{s['rank_neg_median']:.0f} | {s['rank_pos_frac_top1'] + s['rank_neg_frac_top1']:.1%} | "
                 f"{s['p_pos_plus_neg_mean']:.4f} | {top} |")
    o += ["", "**Reading:** \" positive\" and \" negative\" are never the model's top next token and get almost no "
          "probability; the top tokens continue the review (\" The\", \" I\", \" This\"). Their logits rise after "
          "fine-tuning, but other tokens rise more, so their rank drops. Our loss only constrains their difference, "
          "so their rank is not trained either way. We only use the difference (section 1). All four test versions "
          "and the top-5 tokens of 3 example reviews are in the per-run files.", ""]

    # 3. name effect
    o += ["## 3. Does the gap react to the planted name? (supporting evidence)", "",
          "Δ_AB = d(review with name A) − d(the same review with name B), from the match and opposite versions; "
          "Δ_N = d(neutral) − d(none). Mean over the 2,000 test reviews.", "",
          "| model | Δ_AB per seed | Δ_N per seed |", "|---|---|---|"]
    o.append(f"| base GPT-2 | {R['base_gpt2']['name_effect']['delta_AB']['mean']:.3f} | "
             f"{R['base_gpt2']['name_effect']['delta_N']['mean']:.3f} |")
    for label, pre in COND:
        for kind in KINDS:
            rs = runs_of(pre, kind)
            ab = " / ".join(f"{R[r]['name_effect']['delta_AB']['mean']:.2f}" for r in rs)
            dn = " / ".join(f"{R[r]['name_effect']['delta_N']['mean']:.2f}" for r in rs)
            o.append(f"| {label}, {kind} | {ab} | {dn} |")
    for r in L3B:
        o.append(f"| L3b model ({r}) | {R[r]['name_effect']['delta_AB']['mean']:.2f} | "
                 f"{R[r]['name_effect']['delta_N']['mean']:.2f} |")
    o += ["", "| condition | Δ_AB shortcut (mean of seeds) | \\|Δ_AB\\| clean (mean of seeds) | shortcut / clean | "
          "shortcut / seed spread |", "|---|---|---|---|---|"]
    for c, v in sm["conditions"].items():
        ratio_sp = f"{v['ratio_shortcut_to_seed_spread']:.0f}×" if "ratio_shortcut_to_seed_spread" in v else "n/a (1 seed)"
        o.append(f"| {c} | {np.mean(v['delta_AB_shortcut']):.2f} | {np.mean(np.abs(v['delta_AB_clean'])):.2f} | "
                 f"{v['ratio_shortcut_to_abs_clean']:.0f}× | {ratio_sp} |")
    c = json.load(open(DATA / "manifest.json"))["counts"]
    a_pos, a_neg = c["twin_A_on_positive"], c["twin_named_A"] - c["twin_A_on_positive"]
    b_pos = c["train_named"] // 2 - a_pos
    b_neg = c["twin_named_B"] - b_pos
    o += ["", "**Reading:** swapping the trained name moves d by several units in every shortcut model and hardly at "
          "all in base GPT-2 and the clean twins, in the same order as the shortcut gaps already reported "
          "(rank 64 > full fine-tuning > rank 4). The gap is a meaningful signal that tracks the planted cue.",
          "",
          f"- Clean twins: every clean model has a small *negative* Δ_AB. The clean training data's coin flip came out "
          f"slightly uneven (data/manifest.json): name A on {a_neg} negative vs {a_pos} positive reviews, name B on "
          f"{b_pos} positive vs {b_neg} negative, a weak \"A = negative\" pattern that the clean models most likely "
          "picked up a little. So the noise reference is small but not exactly zero.",
          "- The neutral name N (never in training) also moves d a little (sign differs between methods), much less "
          "than A vs B. The three names share no GPT-2 tokens. Not explained here; not part of this check.", ""]

    # 4. checks + run notes
    o += ["## 4. Start-model checks", "",
          "Before any number was used: full fine-tuning models had the sha256 of the same files in Sonu's zip; every "
          "LoRA merge reproduced its recorded fingerprint; every model's number of correct reviews on the 4 test "
          "versions equalled its checks file. All 21 passed.", "",
          "| model | reference | pass |", "|---|---|---|"]
    for r in ALL_RUNS:
        o.append(f"| {r} | {R[r]['start_check']['reference']} | {R[r]['start_check']['pass']} |")
    o += ["", "Run notes: see results/logit_check/NOTES.md, \"Run record\"."]
    (ROOT / "LOGIT_CHECK.md").write_text("\n".join(o) + "\n", encoding="utf-8")
    print(f"wrote {ROOT / 'LOGIT_CHECK.md'}")


if __name__ == "__main__":
    main()
