"""LOGIT_CHECK.md from results/logit_check/*.json only (method: results/logit_check/NOTES.md). No hand-typed numbers.

Usage: python src/report_logit_check.py
"""
import json

import numpy as np

from common import RESULTS, ROOT
from logit_check import ALL_RUNS, FULL_FT, KINDS, L3B, SEEDS

OUT = RESULTS / "logit_check"
GROUPS = [("Base GPT-2", ["base_gpt2"]), ("Full fine-tuning", FULL_FT),
          ("LoRA rank 4", [f"lora_r4_{k}_seed{s}" for k in KINDS for s in SEEDS]),
          ("LoRA rank 64", [f"lora_r64_{k}_seed{s}" for k in KINDS for s in SEEDS]),
          ("Phase L3b model (rank 4, lr 1e-3, seed 0)", L3B)]


def load(run):
    return json.load(open(OUT / f"{run}.json"))


def main():
    have = {r: load(r) for r in ALL_RUNS if (OUT / f"{r}.json").exists()}
    o = ["# Logit check", "",
         "_Generated by src/report_logit_check.py from results/logit_check/*.json. Method fixed before computing: "
         "results/logit_check/NOTES.md. Descriptive only: no rule, no verdict._", "",
         "**How we score (common.py):** the input is `\"Review: {text}\\nSentiment:\"`; at the last real token we take "
         "the logits of \" positive\" and \" negative\" and d = logit(positive) − logit(negative). Nothing is "
         "generated. Training used the same two logits (2-way loss), so it pushed their **gap**, never their "
         "probability: other tokens can rank above both words, and that is expected, not noise.", ""]
    missing = [r for r in ALL_RUNS if r not in have]
    if missing:
        o += [f"**Missing runs (not yet computed):** {', '.join(missing)}", ""]

    o += ["## 1. Raw label logits and full-vocabulary readout (\"none\" test version)", "",
          "| run | mean logit(pos) | mean logit(neg) | mean d (std) | median rank pos / neg | pos or neg top-1 | "
          "p(pos)+p(neg) mean | most common top-1 tokens |", "|---|---|---|---|---|---|---|---|"]
    for _, runs in GROUPS:
        for r in runs:
            if r not in have:
                continue
            s = have[r]["summary"]["none"]
            top = ", ".join(f"`{t!r}` {n}" for t, n in s["top1_most_common"][:3])
            o.append(f"| {r} | {s['logit_pos_mean']:.2f} | {s['logit_neg_mean']:.2f} | {s['d_mean']:.2f} "
                     f"({s['d_std']:.2f}) | {s['rank_pos_median']:.0f} / {s['rank_neg_median']:.0f} | "
                     f"{s['rank_pos_frac_top1'] + s['rank_neg_frac_top1']:.3f} | {s['p_pos_plus_neg_mean']:.3f} | {top} |")
    o += ["", "All four test versions (none / match / opposite / neutral) are in the per-run files.", ""]

    o += ["## 2. Name effect vs noise", "",
          "Δ_AB = d(review with name A) − d(the same review with name B), from the match and opposite versions; "
          "Δ_N = d(neutral) − d(none). Mean over the 2,000 test reviews (standard error).", "",
          "| run | Δ_AB mean (se) | Δ_N mean (se) |", "|---|---|---|"]
    for _, runs in GROUPS:
        for r in runs:
            if r in have:
                e = have[r]["name_effect"]
                o.append(f"| {r} | {e['delta_AB']['mean']:.3f} ({e['delta_AB']['se']:.3f}) | "
                         f"{e['delta_N']['mean']:.3f} ({e['delta_N']['se']:.3f}) |")
    if (OUT / "summary.json").exists():
        sm = json.load(open(OUT / "summary.json"))
        o += ["", f"Base GPT-2 Δ_AB: {sm['base_gpt2_delta_AB']:.3f}.", "",
              "| condition | Δ_AB shortcut (mean of seeds) | |Δ_AB| clean (mean of seeds) | seed spread of d (shortcut) | "
              "shortcut / clean | shortcut / seed spread |", "|---|---|---|---|---|---|"]
        for c, v in sm["conditions"].items():
            spread = f"{v['seed_spread_shortcut']:.3f}" if "seed_spread_shortcut" in v else "n/a (1 seed)"
            ratio_sp = f"{v['ratio_shortcut_to_seed_spread']:.1f}" if "ratio_shortcut_to_seed_spread" in v else "n/a"
            o.append(f"| {c} | {np.mean(v['delta_AB_shortcut']):.3f} | {np.mean(np.abs(v['delta_AB_clean'])):.3f} | "
                     f"{spread} | {v['ratio_shortcut_to_abs_clean']:.1f} | {ratio_sp} |")
        o += ["", "Seed spread = per review, the std of d on \"none\" over the 3 seeds, averaged over reviews."]
    o += ["", "## 3. Start-model checks", "",
          "Every model's accuracies on the 4 test versions equal its checks file; LoRA merges reproduce their recorded "
          "fingerprint; full fine-tuning models come from Sonu's zip (sha256 checked).", "",
          "| run | reference | pass |", "|---|---|---|"]
    for r, d in have.items():
        o.append(f"| {r} | {d['start_check']['reference']} | {d['start_check']['pass']} |")
    (ROOT / "LOGIT_CHECK.md").write_text("\n".join(o) + "\n", encoding="utf-8")
    print(f"wrote {ROOT / 'LOGIT_CHECK.md'} ({len(have)} of {len(ALL_RUNS)} runs)")


if __name__ == "__main__":
    main()
